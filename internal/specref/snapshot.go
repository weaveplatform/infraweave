// Files in the reference directory (api/reference/spacelift).
const (
	FileLock            = "sources.lock.yaml"
	FileIntrospection   = "introspection.json"
	FileBruno           = "bruno.json"
	FileTerraformSchema = "terraform-schema.json"
	FileTerraformOps    = "terraform-operations.json"
	FileMapping         = "rest-mapping.yaml"
	FileSpec            = "spacelift.openapi.yaml"
	FileCoverage        = "coverage.md"
)

// specHeader marks the spec as generated; the mapping is what people edit.
const specHeader = "# Generated by `specref generate` from api/reference/spacelift; edit rest-mapping.yaml, not this file.\n"

// filePerm is owner-only: git records content and the executable bit, not
// the mode, so nothing is lost by keeping generated files private locally.
const filePerm = 0o600

var (
	ErrDrift     = errors.New("committed reference differs from a fresh generation")
	ErrBadCommit = errors.New("bruno ref must be a full 40-character commit SHA")
)

// Lock pins every upstream input of the snapshot.
type Lock struct {
	Introspection LockIntrospection `yaml:"introspection" json:"introspection"`
	Bruno         LockRepo          `yaml:"bruno"         json:"bruno"`
	Provider      LockRepo          `yaml:"provider"      json:"provider"`
}

type LockIntrospection struct {
	Endpoint  string `yaml:"endpoint"  json:"endpoint"`
	SHA256    string `yaml:"sha256"    json:"sha256"`
	FetchedAt string `yaml:"fetchedAt" json:"fetchedAt,omitempty"`
}

type LockRepo struct {
	Repository string `yaml:"repository" json:"repository"`
	Ref        string `yaml:"ref"        json:"ref"`
	SHA256     string `yaml:"sha256"     json:"sha256"`
}

// version names the snapshot by the schema it was generated from, not by
// when it was fetched: a weekly re-fetch of an unchanged schema must leave
// the spec byte-identical, or every refresh would raise a PR.
func (l *Lock) version() string {
	const short = 12
	switch {
	case l == nil || l.Introspection.SHA256 == "":
		return "0.0.0"
	case len(l.Introspection.SHA256) > short:
		return "schema-" + l.Introspection.SHA256[:short]
	default:
		return "schema-" + l.Introspection.SHA256
	}
}

// pins is the lock without the fetch time, for embedding in the spec.
func (l *Lock) pins() *Lock {
	if l == nil {
		return nil
	}
	p := *l
	p.Introspection.FetchedAt = ""
	return &p
}

// ReadSources loads a reference directory.
func ReadSources(dir string) (*Sources, error) {
	root, err := os.OpenRoot(dir)
	if err != nil {
		return nil, fmt.Errorf("open reference dir: %w", err)
	}
	defer root.Close()
	read := func(name string) ([]byte, error) {
		b, err := root.ReadFile(name)
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", name, err)
		}
		return b, nil
	}
	src := &Sources{}
	data, err := read(FileIntrospection)
	if err != nil {
		return nil, err
	}
	if src.Schema, err = ParseIntrospection(data); err != nil {
		return nil, err
	}
	if data, err = read(FileMapping); err != nil {
		return nil, err
	}
	if src.Mapping, err = ParseMapping(data); err != nil {
		return nil, err
	}
	if data, err = read(FileLock); err != nil {
		return nil, err
	}
	src.Lock = &Lock{}
	if err := strictYAML(data, src.Lock); err != nil {
		return nil, fmt.Errorf("%s: %w", FileLock, err)
	}
	for name, dst := range map[string]any{FileBruno: &src.Bruno, FileTerraformSchema: &src.Terraform, FileTerraformOps: &src.TerraformOps} {
		if data, err = read(name); err != nil {
			return nil, err
		}
		if err := json.Unmarshal(data, dst); err != nil {
			return nil, fmt.Errorf("decode %s: %w", name, err)
		}
	}
	return src, nil
}

func strictYAML(data []byte, v any) error {
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	if err := dec.Decode(v); err != nil {
		return fmt.Errorf("decode yaml: %w", err)
	}
	return nil
}

// Generated is the output of one generation.
type Generated struct {
	Spec     []byte
	Coverage []byte
	Report   *Report
}

// Generate derives the spec and coverage report from loaded sources and
// validates the spec as OpenAPI before returning it.
func Generate(ctx context.Context, src *Sources) (*Generated, error) {
	plan, err := BuildPlan(src.Schema, src.Mapping)
	if err != nil {
		return nil, err
	}
	doc, rep, err := BuildOpenAPI(src, plan)
	if err != nil {
		return nil, err
	}
	raw, err := doc.MarshalJSON()
	if err != nil {
		return nil, fmt.Errorf("encode spec: %w", err)
	}
	// Validate what a consumer will load, not the in-memory document: a
	// round trip through the loader resolves every $ref.
	loaded, err := openapi3.NewLoader().LoadFromData(raw)
	if err != nil {
		return nil, fmt.Errorf("load generated spec: %w", err)
	}
	if err := loaded.Validate(ctx, openapi3.DisableExamplesValidation()); err != nil {
		return nil, fmt.Errorf("validate generated spec: %w", err)
	}
	if rep.DroppedExamples = dropInvalidExamples(doc, loaded); len(rep.DroppedExamples) > 0 {
		if raw, err = doc.MarshalJSON(); err != nil {
			return nil, fmt.Errorf("encode spec: %w", err)
		}
	}
	var tree any
	if err := json.Unmarshal(raw, &tree); err != nil {
		return nil, fmt.Errorf("decode spec: %w", err)
	}
	var out bytes.Buffer
	out.WriteString(specHeader)
	enc := yaml.NewEncoder(&out)
	enc.SetIndent(2)
	if err := enc.Encode(tree); err != nil {
		return nil, fmt.Errorf("encode spec yaml: %w", err)
	}
	return &Generated{Spec: out.Bytes(), Coverage: []byte(rep.Markdown()), Report: rep}, nil
}

// GenerateDir regenerates a reference directory in place.
func GenerateDir(ctx context.Context, dir string) (*Generated, error) {
	src, err := ReadSources(dir)
	if err != nil {
		return nil, err
	}
	g, err := Generate(ctx, src)
	if err != nil {
		return nil, err
	}
	return g, writeFiles(dir, map[string][]byte{FileSpec: g.Spec, FileCoverage: g.Coverage})
}

// CheckDir fails with ErrDrift when the committed spec or report is not
// what the committed sources generate.
func CheckDir(ctx context.Context, dir string) error {
	src, err := ReadSources(dir)
	if err != nil {
		return err
	}
	g, err := Generate(ctx, src)
	if err != nil {
		return err
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return fmt.Errorf("open reference dir: %w", err)
	}
	defer root.Close()
	var drift []string
	for name, want := range map[string][]byte{FileSpec: g.Spec, FileCoverage: g.Coverage} {
		got, err := root.ReadFile(name)
		if err != nil || !bytes.Equal(got, want) {
			drift = append(drift, name)
		}
	}
	if len(drift) > 0 {
		return fmt.Errorf("%w: %s (run specref generate)", ErrDrift, strings.Join(drift, ", "))
	}
	return nil
}

// dropInvalidExamples removes request examples their schema rejects and
// returns the operations affected. Bruno's variables lean on GraphQL input
// coercion (a lone value where a list is declared), which JSON Schema does
// not do; such an example would mislead, so it goes and the report says so.
func dropInvalidExamples(built, loaded *openapi3.T) []string {
	var dropped []string
	for path, item := range loaded.Paths.Map() {
		for method, op := range item.Operations() {
			if op.RequestBody == nil || op.RequestBody.Value == nil {
				continue
			}
			mt := op.RequestBody.Value.Content.Get(jsonMedia)
			if mt == nil || mt.Example == nil || mt.Schema == nil || mt.Schema.Value == nil {
				continue
			}
			if mt.Schema.Value.VisitJSON(mt.Example) == nil {
				continue
			}
			built.Paths.Value(path).GetOperation(method).RequestBody.Value.Content.Get(jsonMedia).Example = nil
			dropped = append(dropped, op.OperationID)
		}
	}
	sort.Strings(dropped)
	return dropped
}

func writeFiles(dir string, files map[string][]byte) error {
	root, err := os.OpenRoot(dir)
	if err != nil {
		return fmt.Errorf("open reference dir: %w", err)
	}
	defer root.Close()
	for _, name := range sortedKeys(files) {
		if err := root.WriteFile(name, files[name], filePerm); err != nil {
			return fmt.Errorf("write %s: %w", name, err)
		}
	}
	return nil
}

// FetchOptions say where upstream lives and which versions to pin.
type FetchOptions struct {
	Dir             string
	Endpoint        string
	Codeload        string // base URL serving <repo>/tar.gz/<ref>
	BrunoRepo       string
	BrunoRef        string
	ProviderRepo    string
	ProviderVersion string
	Terraform       string
	Fetcher         *Fetcher
	Run             CommandRunner
	Now             func() time.Time
}

var commitSHA = regexp.MustCompile(`^[0-9a-f]{40}$`)

// Fetch refreshes every snapshot and the lock from upstream. It writes
// nothing unless every source was fetched and parsed, so a failed refresh
// never leaves a half-updated directory.
func Fetch(ctx context.Context, o FetchOptions) error {
	if !commitSHA.MatchString(o.BrunoRef) {
		return fmt.Errorf("%w: %q", ErrBadCommit, o.BrunoRef)
	}
	raw, err := o.Fetcher.Introspect(ctx, o.Endpoint)
	if err != nil {
		return err
	}
	schema, err := ParseIntrospection(raw)
	if err != nil {
		return err
	}
	schema.Normalize()
	intro, err := MarshalIntrospection(schema)
	if err != nil {
		return err
	}

	brunoTGZ, err := o.Fetcher.Get(
		ctx,
		fmt.Sprintf("%s/%s/tar.gz/%s", o.Codeload, o.BrunoRepo, o.BrunoRef),
	)
	if err != nil {
		return err
	}
	inv, err := ReadBrunoTarball(brunoTGZ)
	if err != nil {
		return err
	}

	providerTGZ, err := o.Fetcher.Get(
		ctx,
		fmt.Sprintf("%s/%s/tar.gz/refs/tags/v%s", o.Codeload, o.ProviderRepo, o.ProviderVersion),
	)
	if err != nil {
		return err
	}
	ops, err := ReadProviderTarball(providerTGZ)
	if err != nil {
		return err
	}
	ops.RetainRootFields(schema)

	tfRaw, err := FetchTerraformSchema(ctx, o.Run, o.Terraform, o.ProviderVersion)
	if err != nil {
		return err
	}
	tf, err := ParseTerraformSchema(tfRaw)
	if err != nil {
		return err
	}

	lock := Lock{
		Introspection: LockIntrospection{
			Endpoint:  o.Endpoint,
			SHA256:    digest(intro),
			FetchedAt: o.Now().UTC().Format(time.RFC3339),
		},
		Bruno: LockRepo{Repository: o.BrunoRepo, Ref: o.BrunoRef, SHA256: digest(brunoTGZ)},
		Provider: LockRepo{
			Repository: o.ProviderRepo,
			Ref:        "v" + o.ProviderVersion,
			SHA256:     digest(providerTGZ),
		},
	}
	files := map[string][]byte{FileIntrospection: intro}
	for name, v := range map[string]any{FileBruno: inv, FileTerraformOps: ops, FileTerraformSchema: tf} {
		if files[name], err = marshalJSON(v); err != nil {
			return err
		}
	}
	var lockBuf bytes.Buffer
	lockBuf.WriteString(
		"# Written by `specref fetch`; pins every upstream input of this directory.\n",
	)
	enc := yaml.NewEncoder(&lockBuf)
	enc.SetIndent(2)
	if err := enc.Encode(lock); err != nil {
		return fmt.Errorf("encode lock: %w", err)
	}
	files[FileLock] = lockBuf.Bytes()
	return writeFiles(o.Dir, files)
}

func marshalJSON(v any) ([]byte, error) {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode json: %w", err)
	}
	return append(b, '\n'), nil
}

func digest(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}
