const fileInventory = "29-data-model-inventory.md"

func TestUnitInventoryGolden(t *testing.T) {
	dir := writeFixtureDir(t)
	out := filepath.Join(t.TempDir(), fileInventory)
	if err := InventoryFile(dir, out); err != nil {
		t.Fatal(err)
	}
	first, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	golden(t, fileInventory, first)
	if err := CheckInventory(dir, out); err != nil {
		t.Errorf("check right after write: %v", err)
	}
	if err := InventoryFile(dir, out); err != nil {
		t.Fatal(err)
	}
	if second, err := os.ReadFile(out); err != nil || !bytes.Equal(first, second) {
		t.Errorf("regenerating changed the bytes (err %v)", err)
	}
}

// TestUnitInventorySemantics asserts what the golden file encodes, so a
// reviewer of an -update diff knows what must still hold.
func TestUnitInventorySemantics(t *testing.T) {
	md := string(Inventory(fixtureSchema(), fixtureLock()))
	for _, want := range []string{
		"# 29: Data model inventory\n",
		"Checked against: the introspection snapshot `abc` (fetched 2026-10-28T06:58:57Z)",
		"Research baseline: **2026-10-28**.",
		"Generated by `make reference-inventory` from `api/reference/spacelift/introspection.json`; do not edit.",
		"[28](28-data-model.md)",
		"| Object types | 13 | 68 |",
		"| Unions | 1 | 2 |",
		"\n### Stack\n\n| Field | Type | Nullable | Deprecated |",
		"| `labels` | `[String!]!` | no |  |",
		"| `runs(before: String)` | `[Run!]!` | no |  |",
		"| `latestRun` | `Run` | yes |  |",
		"| `legacy` | `String` | yes | gone |",
		"| `autodeploy` | `Boolean!` | no | `false` |",
		"| `space` | `ID` | yes |  |",
		"One of `User`, `Team`.",
		"| `OLD` | unused |",
		"`Boolean`, `Float`, `ID`, `Int`, `String`.",
		"\n## Sources\n",
	} {
		if !strings.Contains(md, want) {
			t.Errorf("inventory lacks %q", want)
		}
	}
	if strings.Contains(md, "The stack name.") || strings.Contains(md, "A stack.") {
		t.Error("inventory carries upstream descriptions")
	}
	sections := []string{
		"## Object types",
		"## Interfaces",
		"## Unions",
		"## Input objects",
		"## Enums",
		"## Scalars",
		"## Sources",
	}
	last := -1
	for _, s := range sections {
		i := strings.Index(md, "\n"+s+"\n")
		if i <= last {
			t.Errorf("section %q out of order", s)
		}
		last = i
	}
}

func TestUnitInventoryEdges(t *testing.T) {
	s := fixtureSchema()
	s.Types = append(s.Types,
		&Type{Kind: KindObject, Name: "__Type", Fields: []Field{field("kind", tString)}},
		&Type{
			Kind:          KindInterface,
			Name:          "Node",
			Fields:        []Field{field("id", nn(tID))},
			PossibleTypes: []TypeRef{obj("Stack")},
		},
	)
	stack := s.Type("Stack")
	stack.Interfaces = []TypeRef{named(KindInterface, "Node")}
	stack.Fields = append(
		stack.Fields,
		deprecated(
			field(
				"old",
				tString,
				InputValue{Name: "first", Type: tInt, DefaultValue: strPtr("10")},
			),
			"",
		),
		deprecated(field("piped", tString), "Use a | b\ninstead."),
	)
	md := string(Inventory(s, nil))
	for _, want := range []string{
		"Checked against: the introspection snapshot `not recorded` (fetched not recorded)",
		"Research baseline: **not recorded**.",
		"\n### Node\n\nImplemented by `Stack`.\n\n| Field |",
		"\n### Stack\n\nImplements `Node`.\n\n| Field |",
		"| `old(first: Int = 10)` | `String` | yes | yes |",
		`| ` + "`piped`" + ` | ` + "`String`" + ` | yes | Use a \| b instead. |`,
		"| Interfaces | 1 | 1 |",
	} {
		if !strings.Contains(md, want) {
			t.Errorf("inventory lacks %q", want)
		}
	}
	if strings.Contains(md, "__Type") {
		t.Error("inventory lists GraphQL's own introspection types")
	}
	long := fixtureLock()
	long.Introspection.SHA256 = "b3255fe38f5ef8e08dfaf4fcabc47b12"
	long.Introspection.Endpoint = ""
	md = string(Inventory(fixtureSchema(), long))
	if !strings.Contains(md, "snapshot `b3255fe38f5e`") ||
		!strings.Contains(
			md,
			"introspection of not recorded, sha256 `b3255fe38f5ef8e08dfaf4fcabc47b12`",
		) {
		t.Errorf("long sha: %s", md[:400])
	}
}

func TestUnitInventoryErrors(t *testing.T) {
	dir := writeFixtureDir(t)
	out := filepath.Join(t.TempDir(), fileInventory)
	if err := CheckInventory(dir, out); !errors.Is(err, ErrDrift) {
		t.Errorf("missing report: err = %v, want ErrDrift", err)
	}
	if err := os.WriteFile(out, []byte("edited\n"), filePerm); err != nil {
		t.Fatal(err)
	}
	if err := CheckInventory(dir, out); !errors.Is(err, ErrDrift) ||
		!strings.Contains(err.Error(), out) {
		t.Errorf("edited report: err = %v, want drift in %s", err, out)
	}
	if err := InventoryFile(dir, filepath.Join(out, "not-a-dir", "x.md")); err == nil {
		t.Error("unwritable out: want error")
	}
	missing := filepath.Join(t.TempDir(), "missing")
	if err := InventoryFile(missing, out); err == nil {
		t.Error("InventoryFile missing dir: want error")
	}
	if err := CheckInventory(missing, out); err == nil || errors.Is(err, ErrDrift) {
		t.Errorf("CheckInventory missing dir: err = %v, want a read error", err)
	}
}
