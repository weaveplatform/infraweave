// Discriminator is the property that names the concrete type of a union or
// interface member, standing in for GraphQL's __typename.
const Discriminator = "kind"

const (
	problemSchema = "Problem"
	problemMedia  = "application/problem+json"
	jsonMedia     = "application/json"
)

var (
	ErrUnknownScalar      = errors.New("scalar has no OpenAPI mapping")
	ErrDiscriminatorClash = errors.New("union member already has a kind field")
	ErrComponentClash     = errors.New("generated component name collides with a GraphQL type")
)

// Sources is everything a reference is generated from.
type Sources struct {
	Schema       *Schema
	Mapping      *Mapping
	Bruno        *BrunoInventory
	Terraform    *TerraformSchema
	TerraformOps *TerraformOperations
	Lock         *Lock
}

// builder turns a Plan into an OpenAPI document, emitting only the GraphQL
// types some route reaches.
type builder struct {
	src     *Sources
	plan    *Plan
	doc     *openapi3.T
	queue   []string
	queued  map[string]bool
	members map[string]bool // object types that need the kind discriminator
	tf      *tfIndex
	bruno   map[string]*BrunoOperation
	bodies  map[string]string // <Input>Body component → the field path it drops
}

func newBuilder(src *Sources, plan *Plan) *builder {
	b := &builder{
		src:     src,
		plan:    plan,
		queued:  map[string]bool{},
		members: map[string]bool{},
		bruno:   pickBrunoRequests(src.Bruno),
		bodies:  map[string]string{},
	}
	for _, t := range src.Schema.Types {
		if t.Kind == KindUnion || t.Kind == KindInterface {
			for _, m := range t.PossibleTypes {
				b.members[m.Name] = true
			}
		}
	}
	return b
}

// BuildOpenAPI renders the plan as an OpenAPI 3.0.3 document.
func BuildOpenAPI(src *Sources, plan *Plan) (*openapi3.T, *Report, error) {
	b := newBuilder(src, plan)
	b.tf = indexTerraform(src, plan)
	b.doc = &openapi3.T{
		OpenAPI: "3.0.3",
		Info: &openapi3.Info{
			Title:   "Spacelift API reference (REST projection)",
			Version: src.Lock.version(),
			Description: "The Spacelift GraphQL API projected onto resource-oriented REST routes. " +
				"Generated by `specref generate` from the pinned introspection snapshot, the " +
				"spacelift-api-bruno collection and the Spacelift Terraform provider; see " +
				"docs/research/02-graphql-to-rest-mapping.md. Every operation names the GraphQL " +
				"field it stands for in `x-graphql`.",
			Extensions: map[string]any{"x-sources": src.Lock.pins()},
		},
		Paths: openapi3.NewPaths(),
		Components: &openapi3.Components{
			Schemas:         openapi3.Schemas{},
			Responses:       openapi3.ResponseBodies{},
			SecuritySchemes: openapi3.SecuritySchemes{},
		},
		Security: openapi3.SecurityRequirements{{"bearerAuth": []string{}}},
	}
	b.addCommon()
	tags := map[string]bool{}
	for _, r := range plan.Routes {
		op, err := b.operation(r)
		if err != nil {
			return nil, nil, err
		}
		for _, t := range op.Tags {
			tags[t] = true
		}
		item := b.doc.Paths.Value(r.Path)
		if item == nil {
			item = &openapi3.PathItem{}
			b.doc.Paths.Set(r.Path, item)
		}
		item.SetOperation(r.Method, op)
	}
	if err := b.drain(); err != nil {
		return nil, nil, err
	}
	b.addTags(tags)
	return b.doc, b.report(), nil
}

func (b *builder) addCommon() {
	b.doc.Components.SecuritySchemes["bearerAuth"] = &openapi3.SecuritySchemeRef{
		Value: &openapi3.SecurityScheme{
			Type: "http", Scheme: "bearer", BearerFormat: "JWT",
			Description: "A JWT from POST /auth/token (upstream: the apiKeyUser mutation).",
		},
	}
	b.doc.Components.Schemas[problemSchema] = &openapi3.SchemaRef{Value: &openapi3.Schema{
		Type:        &openapi3.Types{openapi3.TypeObject},
		Description: "An RFC 9457 problem detail. GraphQL reports failures as HTTP 200 with an errors array; REST uses the status code and this body.",
		Properties: openapi3.Schemas{
			"type":     openapi3.NewStringSchema().NewRef(),
			"title":    openapi3.NewStringSchema().NewRef(),
			"status":   openapi3.NewInt32Schema().NewRef(),
			"detail":   openapi3.NewStringSchema().NewRef(),
			"instance": openapi3.NewStringSchema().NewRef(),
		},
		Required: []string{"title", "status"},
	}}
	desc := "The request failed; the body says why."
	b.doc.Components.Responses[problemSchema] = &openapi3.ResponseRef{Value: &openapi3.Response{
		Description: &desc,
		Content: openapi3.Content{
			problemMedia: openapi3.NewMediaType().WithSchemaRef(componentRef(problemSchema)),
		},
	}}
	notFound := "No such resource, or the caller may not see it."
	b.doc.Components.Responses["NotFound"] = &openapi3.ResponseRef{Value: &openapi3.Response{
		Description: &notFound,
		Content: openapi3.Content{
			problemMedia: openapi3.NewMediaType().WithSchemaRef(componentRef(problemSchema)),
		},
	}}
}

func componentRef(name string) *openapi3.SchemaRef {
	return &openapi3.SchemaRef{Ref: "#/components/schemas/" + name}
}

func (b *builder) enqueue(name string) {
	if !b.queued[name] {
		b.queued[name] = true
		b.queue = append(b.queue, name)
	}
}

// typeSchema maps a named GraphQL type to a schema reference. Inside an
// object an addressable resource is embedded as a <Type>Ref holding its id,
// which keeps payloads finite where GraphQL would recurse (Stack → Run →
// Stack).
func (b *builder) typeSchema(t TypeRef, embedded bool) (*openapi3.SchemaRef, error) {
	if t.Kind == KindScalar {
		return scalarSchema(t.Name)
	}
	if _, ok := b.plan.ItemTypes[t.Name]; ok && embedded {
		if b.src.Schema.Type(t.Name+"Ref") != nil {
			return nil, fmt.Errorf("%w: %sRef", ErrComponentClash, t.Name)
		}
		b.enqueue(t.Name + "Ref")
		return componentRef(t.Name + "Ref"), nil
	}
	b.enqueue(t.Name)
	return componentRef(t.Name), nil
}

func scalarSchema(name string) (*openapi3.SchemaRef, error) {
	switch name {
	case "ID", "String":
		return openapi3.NewStringSchema().NewRef(), nil
	case "Int":
		return openapi3.NewInt32Schema().NewRef(), nil
	case "Float":
		return openapi3.NewFloat64Schema().NewRef(), nil
	case "Boolean":
		return openapi3.NewBoolSchema().NewRef(), nil
	}
	return nil, fmt.Errorf("%w: %s", ErrUnknownScalar, name)
}

// schemaFor maps any GraphQL type, unwrapping NON_NULL and LIST.
func (b *builder) schemaFor(t TypeRef, embedded bool) (*openapi3.SchemaRef, error) {
	if t.Kind == KindNonNull {
		return b.schemaFor(*t.OfType, embedded)
	}
	if t.Kind == KindList {
		items, err := b.schemaFor(*t.OfType, embedded)
		if err != nil {
			return nil, err
		}
		return &openapi3.SchemaRef{
			Value: &openapi3.Schema{Type: &openapi3.Types{openapi3.TypeArray}, Items: items},
		}, nil
	}
	return b.typeSchema(t, embedded)
}

// property is schemaFor plus the description and nullability a field adds.
// Nullability is only expressible on inline schemas in OpenAPI 3.0 (a $ref
// takes no siblings), so a nullable reference shows as "not required" only.
func (b *builder) property(t TypeRef, desc string, deprecated bool) (*openapi3.SchemaRef, error) {
	ref, err := b.schemaFor(t, true)
	if err != nil {
		return nil, err
	}
	if ref.Ref != "" {
		return ref, nil
	}
	ref.Value.Description = desc
	ref.Value.Deprecated = deprecated
	ref.Value.Nullable = !t.NonNull()
	return ref, nil
}

func (b *builder) drain() error {
	for len(b.queue) > 0 {
		name := b.queue[0]
		b.queue = b.queue[1:]
		s, err := b.component(name)
		if err != nil {
			return err
		}
		if _, clash := b.doc.Components.Schemas[name]; clash {
			return fmt.Errorf("%w: %s", ErrComponentClash, name)
		}
		b.doc.Components.Schemas[name] = s
	}
	return nil
}

func (b *builder) component(name string) (*openapi3.SchemaRef, error) {
	t := b.src.Schema.Type(name)
	if t == nil {
		base := strings.TrimSuffix(name, "Ref")
		return b.refSchema(base, b.plan.ItemTypes[base]), nil
	}
	switch t.Kind {
	case KindEnum:
		return enumSchema(t), nil
	case KindUnion, KindInterface:
		return b.polymorphic(t)
	case KindInputObject:
		return b.inputObject(t)
	default:
		return b.object(t)
	}
}

func (b *builder) refSchema(typeName string, item *Route) *openapi3.SchemaRef {
	return &openapi3.SchemaRef{Value: &openapi3.Schema{
		Type: &openapi3.Types{openapi3.TypeObject},
		Description: fmt.Sprintf(
			"A reference to a %s; fetch it with %s %s.",
			typeName,
			item.Method,
			item.Path,
		),
		Properties: openapi3.Schemas{"id": openapi3.NewStringSchema().NewRef()},
		Required:   []string{"id"},
		Extensions: map[string]any{"x-graphql-type": typeName},
	}}
}

func enumSchema(t *Type) *openapi3.SchemaRef {
	s := openapi3.NewStringSchema()
	s.Description = t.Description
	descs := map[string]string{}
	var deprecated []string
	for _, v := range t.EnumValues {
		s.Enum = append(s.Enum, v.Name)
		if v.Description != "" {
			descs[v.Name] = v.Description
		}
		if v.IsDeprecated {
			deprecated = append(deprecated, v.Name)
		}
	}
	s.Extensions = map[string]any{"x-graphql-type": t.Name}
	if len(descs) > 0 {
		s.Extensions["x-enum-descriptions"] = descs
	}
	if len(deprecated) > 0 {
		s.Extensions["x-enum-deprecated"] = deprecated
	}
	return s.NewRef()
}

func (b *builder) polymorphic(t *Type) (*openapi3.SchemaRef, error) {
	s := &openapi3.Schema{
		Description: t.Description,
		Discriminator: &openapi3.Discriminator{
			PropertyName: Discriminator,
			Mapping:      map[string]openapi3.MappingRef{},
		},
		Extensions: map[string]any{"x-graphql-type": t.Name, "x-graphql-kind": t.Kind},
	}
	for _, m := range t.PossibleTypes {
		ref, err := b.typeSchema(TypeRef{Kind: KindObject, Name: m.Name}, false)
		if err != nil {
			return nil, err
		}
		s.OneOf = append(s.OneOf, ref)
		s.Discriminator.Mapping[m.Name] = openapi3.MappingRef{Ref: ref.Ref}
	}
	return s.NewRef(), nil
}

func (b *builder) object(t *Type) (*openapi3.SchemaRef, error) {
	s := &openapi3.Schema{
		Type:        &openapi3.Types{openapi3.TypeObject},
		Description: t.Description,
		Properties:  openapi3.Schemas{},
		Extensions:  map[string]any{"x-graphql-type": t.Name},
	}
	omitted := map[string]string{}
	_, isItem := b.plan.ItemTypes[t.Name]
	for _, f := range t.Fields {
		if len(f.Args) > 0 || isItem && f.Type.IsList() && b.isItemType(f.Type) {
			omitted[f.Name] = b.omittedReason(t.Name, f)
			continue
		}
		if f.Name == Discriminator && b.members[t.Name] {
			return nil, fmt.Errorf("%w: %s", ErrDiscriminatorClash, t.Name)
		}
		p, err := b.property(f.Type, f.Description, f.IsDeprecated)
		if err != nil {
			return nil, err
		}
		s.Properties[f.Name] = p
		if f.Type.NonNull() {
			s.Required = append(s.Required, f.Name)
		}
	}
	if b.members[t.Name] {
		kind := openapi3.NewStringSchema()
		kind.Enum = []any{t.Name}
		kind.Description = "The concrete type, for union and interface responses."
		s.Properties[Discriminator] = kind.NewRef()
		s.Required = append(s.Required, Discriminator)
	}
	if len(omitted) > 0 {
		s.Extensions["x-graphql-omitted"] = omitted
	}
	sort.Strings(s.Required)
	return s.NewRef(), nil
}

func (b *builder) isItemType(t TypeRef) bool {
	_, ok := b.plan.ItemTypes[t.Named().Name]
	return ok
}

func (b *builder) omittedReason(owner string, f Field) string {
	for _, r := range b.plan.Routes {
		if r.Style == StyleField && r.OwnerType == owner && r.Field.Name == f.Name {
			return "served by " + r.Method + " " + r.Path
		}
	}
	return "takes arguments; not reachable from an item route"
}

func (b *builder) inputObject(t *Type) (*openapi3.SchemaRef, error) {
	s := &openapi3.Schema{
		Type:        &openapi3.Types{openapi3.TypeObject},
		Description: t.Description,
		Properties:  openapi3.Schemas{},
		Extensions:  map[string]any{"x-graphql-type": t.Name},
	}
	for _, f := range t.InputFields {
		p, err := b.inputProperty(t.Name, f)
		if err != nil {
			return nil, err
		}
		s.Properties[f.Name] = p
		if f.Type.NonNull() && f.DefaultValue == nil {
			s.Required = append(s.Required, f.Name)
		}
	}
	sort.Strings(s.Required)
	return s.NewRef(), nil
}

// inputProperty renders an input field or argument, folding in the
// Terraform provider's attribute when one maps to it.
func (b *builder) inputProperty(owner string, f InputValue) (*openapi3.SchemaRef, error) {
	desc := f.Description
	attrs := b.tf.attributes(owner, f.Name)
	if desc == "" && len(attrs) > 0 {
		desc = attrs[0].Description
	}
	p, err := b.property(f.Type, desc, false)
	if err != nil {
		return nil, err
	}
	if p.Ref != "" && len(attrs) == 0 && f.DefaultValue == nil {
		return p, nil
	}
	if p.Ref != "" {
		// A $ref takes no siblings in 3.0; wrap it to carry the default
		// and the extension.
		p = &openapi3.SchemaRef{
			Value: &openapi3.Schema{AllOf: openapi3.SchemaRefs{p}, Description: desc},
		}
	}
	if f.DefaultValue != nil {
		p.Value.Default = graphqlLiteral(*f.DefaultValue)
	}
	if len(attrs) > 0 {
		p.Value.Extensions = map[string]any{"x-terraform": terraformNames(attrs)}
	}
	return p, nil
}

func terraformNames(attrs []tfAttribute) []string {
	names := make([]string, len(attrs))
	for i, a := range attrs {
		names[i] = a.Resource + "." + a.Attribute
	}
	sort.Strings(names)
	return names
}

// graphqlLiteral converts a GraphQL default value to JSON where they agree;
// an enum literal (unquoted name) becomes its string.
func graphqlLiteral(lit string) any {
	var v any
	if json.Unmarshal([]byte(lit), &v) == nil {
		return v
	}
	return lit
}

func (b *builder) operation(r *Route) (*openapi3.Operation, error) {
	bru := b.bruno[r.Field.Name]
	if r.Style == StyleField {
		bru = nil
	}
	op := &openapi3.Operation{
		OperationID: r.OperationID,
		Summary:     summary(r, bru),
		Description: r.Field.Description,
		Responses:   openapi3.NewResponses(),
		Extensions: map[string]any{
			"x-graphql": map[string]string{
				"operation": r.Op,
				"type":      r.OwnerType,
				"field":     r.Field.Name,
			},
			"x-rest-style": r.Style,
		},
	}
	if op.Description == "" && bru != nil {
		op.Description = bru.Docs
	}
	if bru != nil {
		op.Extensions["x-bruno"] = bru.Path
	}
	if tag := b.tagFor(r, bru); tag != "" {
		op.Tags = []string{tag}
	}
	if r.Public {
		op.Security = &openapi3.SecurityRequirements{}
	}
	if err := b.parameters(r, op); err != nil {
		return nil, err
	}
	if err := b.requestBody(r, op, bru); err != nil {
		return nil, err
	}
	return op, b.responses(r, op)
}

func summary(r *Route, bru *BrunoOperation) string {
	if bru != nil && bru.Name != "" {
		return bru.Name
	}
	ws := words(r.OperationID)
	ws[0] = upperFirst(ws[0])
	for i := 1; i < len(ws); i++ {
		if strings.ToUpper(ws[i]) != ws[i] {
			ws[i] = strings.ToLower(ws[i])
		}
	}
	return strings.Join(ws, " ")
}

func (b *builder) parameters(r *Route, op *openapi3.Operation) error {
	for _, pp := range r.Params {
		desc := "Selects the parent object."
		ext := map[string]any{}
		if pp.Arg != "" {
			if a := b.src.Schema.argPath(r.Field, pp.Arg); a != nil {
				desc = a.Description
			}
			ext["x-graphql-arg"] = pp.Arg
			if attrs := b.tf.attributes("path:"+r.OperationID, pp.Arg); len(attrs) > 0 {
				if desc == "" {
					desc = attrs[0].Description
				}
				ext["x-terraform"] = terraformNames(attrs)
			}
		}
		p := openapi3.NewPathParameter(pp.Name).WithSchema(openapi3.NewStringSchema())
		p.Description = desc
		p.Extensions = ext
		op.AddParameter(p)
	}
	if r.HasBody() {
		return nil
	}
	for _, a := range r.Field.Args {
		if r.Bound(a.Name) {
			continue
		}
		p := &openapi3.Parameter{
			In:          openapi3.ParameterInQuery,
			Name:        a.Name,
			Description: a.Description,
			Required: a.Type.NonNull() &&
				a.DefaultValue == nil,
			Extensions: map[string]any{"x-graphql-arg": a.Name},
		}
		s, err := b.schemaFor(a.Type, false)
		if err != nil {
			return err
		}
		if k := b.src.Schema.Type(a.Type.Named().Name); k != nil && k.Kind == KindInputObject {
			// Structured arguments of a read travel JSON-encoded in one
			// query parameter rather than forcing the read into a POST.
			p.Content = openapi3.Content{jsonMedia: openapi3.NewMediaType().WithSchemaRef(s)}
		} else {
			p.Schema = s
		}
		op.AddParameter(p)
	}
	return nil
}

func (b *builder) requestBody(r *Route, op *openapi3.Operation, bru *BrunoOperation) error {
	if !r.HasBody() {
		return nil
	}
	var args []InputValue
	for _, a := range r.Field.Args {
		if !r.Bound(a.Name) {
			args = append(args, a)
		}
	}
	if len(args) == 0 {
		return nil
	}
	inPath := map[string][]string{}
	for _, pp := range r.Params {
		if arg, rest, ok := strings.Cut(pp.Arg, "."); ok {
			inPath[arg] = strings.Split(rest, ".")
		}
	}
	var schema *openapi3.SchemaRef
	required := false
	var bodyArg string
	if len(args) == 1 && b.src.Schema.Type(args[0].Type.Named().Name) != nil &&
		b.src.Schema.Type(args[0].Type.Named().Name).Kind == KindInputObject &&
		!args[0].Type.IsList() {
		var err error
		if path, ok := inPath[args[0].Name]; ok {
			schema, err = b.bodyComponent(b.src.Schema.Type(args[0].Type.Named().Name), path)
			required = true
		} else {
			schema, err = b.schemaFor(args[0].Type, false)
			required = args[0].Type.NonNull()
		}
		if err != nil {
			return err
		}
		bodyArg = args[0].Name
	} else {
		name := upperFirst(r.OperationID) + "Request"
		if b.src.Schema.Type(name) != nil {
			return fmt.Errorf("%w: %s", ErrComponentClash, name)
		}
		s := &openapi3.Schema{
			Type: &openapi3.Types{openapi3.TypeObject}, Properties: openapi3.Schemas{},
			Description: "The arguments of " + r.Field.Name + " not carried in the path.",
			Extensions:  map[string]any{"x-graphql-args-of": r.Field.Name},
		}
		for _, a := range args {
			if path, ok := inPath[a.Name]; ok {
				p, err := b.bodyComponent(b.src.Schema.Type(a.Type.Named().Name), path)
				if err != nil {
					return err
				}
				s.Properties[a.Name] = p
				s.Required = append(s.Required, a.Name)
				required = true
				continue
			}
			p, err := b.inputProperty(name, a)
			if err != nil {
				return err
			}
			s.Properties[a.Name] = p
			if a.Type.NonNull() && a.DefaultValue == nil {
				s.Required = append(s.Required, a.Name)
				required = true
			}
		}
		sort.Strings(s.Required)
		b.doc.Components.Schemas[name] = s.NewRef()
		schema = componentRef(name)
	}
	mt := openapi3.NewMediaType().WithSchemaRef(schema)
	if ex := exampleFor(bru, bodyArg, args, inPath); ex != nil {
		mt.Example = ex
	}
	body := openapi3.NewRequestBody().
		WithContent(openapi3.Content{jsonMedia: mt}).
		WithRequired(required)
	if bodyArg != "" {
		body.Extensions = map[string]any{"x-graphql-arg": bodyArg}
	}
	op.RequestBody = &openapi3.RequestBodyRef{Value: body}
	return nil
}

// exampleFor lifts a request example out of the Bruno variables: the one
// input argument's value, or the unbound arguments as an object.
func exampleFor(
	bru *BrunoOperation,
	bodyArg string,
	args []InputValue,
	inPath map[string][]string,
) any {
	if bru == nil || len(bru.Variables) == 0 {
		return nil
	}
	var vars map[string]any
	if json.Unmarshal(bru.Variables, &vars) != nil {
		return nil
	}
	for arg, path := range inPath {
		if bodyArg == "" {
			dropPath(vars, append([]string{arg}, path...))
		} else {
			dropPath(vars[arg], path)
		}
	}
	if bodyArg != "" {
		return vars[bodyArg]
	}
	out := map[string]any{}
	for _, a := range args {
		if v, ok := vars[a.Name]; ok {
			out[a.Name] = v
		}
	}
	if len(out) == 0 {
		return nil
	}
	return out
}

func (b *builder) responses(r *Route, op *openapi3.Operation) error {
	s, err := b.schemaFor(r.Field.Type, false)
	if err != nil {
		return err
	}
	code, desc := http.StatusOK, "The "+r.Field.Name+" result."
	if r.Style == StyleCreate || r.Created {
		code, desc = http.StatusCreated, "Created."
	}
	op.Responses.Set(
		fmt.Sprint(code),
		&openapi3.ResponseRef{Value: openapi3.NewResponse().WithDescription(desc).
			WithContent(openapi3.Content{jsonMedia: openapi3.NewMediaType().WithSchemaRef(s)})},
	)
	if len(r.Params) > 0 {
		op.Responses.Set("404", &openapi3.ResponseRef{Ref: "#/components/responses/NotFound"})
	}
	op.Responses.Set(
		"default",
		&openapi3.ResponseRef{Ref: "#/components/responses/" + problemSchema},
	)
	return nil
}

// dropPath deletes the value at path from a decoded JSON object, so an
// example omits the value its route carries in the URL.
func dropPath(v any, path []string) {
	m, ok := v.(map[string]any)
	if !ok {
		return
	}
	if len(path) == 1 {
		delete(m, path[0])
		return
	}
	dropPath(m[path[0]], path[1:])
}

// bodyComponent renders input type t without the field at path, which the
// route carries in its URL: ManagedUserUpdateInputBody is
// ManagedUserUpdateInput less id. Inputs on the way to that field become
// required, because the server needs them to put the id back.
func (b *builder) bodyComponent(t *Type, path []string) (*openapi3.SchemaRef, error) {
	name := t.Name + "Body"
	want := strings.Join(path, ".")
	if got, ok := b.bodies[name]; ok {
		if got != want {
			return nil, fmt.Errorf(
				"%w: %s drops both %s and %s",
				ErrComponentClash,
				name,
				got,
				want,
			)
		}
		return componentRef(name), nil
	}
	if b.src.Schema.Type(name) != nil {
		return nil, fmt.Errorf("%w: %s", ErrComponentClash, name)
	}
	b.bodies[name] = want
	ref, err := b.inputObject(t)
	if err != nil {
		return nil, err
	}
	s := ref.Value
	s.Extensions["x-graphql-in-path"] = want
	if len(path) == 1 {
		delete(s.Properties, path[0])
		s.Required = slices.DeleteFunc(s.Required, func(n string) bool { return n == path[0] })
	} else {
		child, err := b.bodyComponent(
			b.src.Schema.Type(inputField(t, path[0]).Type.Named().Name),
			path[1:],
		)
		if err != nil {
			return nil, err
		}
		s.Properties[path[0]] = child
		if !slices.Contains(s.Required, path[0]) {
			s.Required = append(s.Required, path[0])
			sort.Strings(s.Required)
		}
	}
	if len(s.Required) == 0 {
		s.Required = nil
	}
	b.doc.Components.Schemas[name] = ref
	return componentRef(name), nil
}
