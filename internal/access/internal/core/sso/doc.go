// Package sso holds an organization's identity providers: its OIDC, SAML
// and GitHub OAuth sign-in front ends, any number of each kind, one per
// kind its default. Service lists, creates, changes and deletes them and
// chooses the default per kind for the Organization tag, admitting only
// the principals orgadmin admits. A provider is stored disabled; a first
// sign-in through it enables it and records its login as AdminLogin.
//
// Each kind takes its own Settings, and a setting of another kind is
// refused: OIDC an https issuer and a client ID; SAML exactly one of
// metadata XML and an https metadata URL, and a NameID format (TRANSIENT
// by default, EMAIL_ADDRESS or PERSISTENT), whose subject attribute the
// claim mapping must name unless it is PERSISTENT; GitHub OAuth a base URL
// (https://github.com by default), a client ID and the GitHub
// organization's login. The claim mapping maps the targets subject, login,
// name, email and groups to claims; Claims applies the defaults (an OIDC
// subject from sub, login from preferred_username, then email, then sub,
// groups from groups). The issuer, client ID, kind, NameID format, base URL
// and GitHub organization never change: Settings.Change refuses another
// value, as a provider is deleted and created again instead. Invalid input
// is a FieldError of the organization package, naming the field.
//
// FirstOfKind makes the first provider of a kind its default, and
// Successor the oldest remaining one when the default is deleted. Creating
// an OIDC provider needs the oidc-sso feature and a SAML provider
// saml-sso, checked through the features domain; a SAML provider's
// service provider signing key is generated by NewSigningKey, RSA-2048
// from crypto/rsa, and stored as its secret. Every change carries its
// organization trail entry, and deleting a provider drops the sessions
// the store revokes from the replica's cache at once.
//
// For the SSO tag, Service addresses the organization's default OIDC
// provider: OIDCSettings reads it; CreateOIDC creates it, disabled and
// named after its host, once its discovery document reads through
// Discovery with the exact issuer, refusing a second with
// ErrDefaultExists, which the store also holds under the organization's
// lock; UpdateOIDC replaces its claim mapping, leaving it enabled or not;
// DeleteOIDC deletes it as Delete does. Their FieldErrors name the tag's
// body fields, clientCredentials for the secret. HasSSO reports an
// enabled OIDC or SAML provider.
//
// SignIn signs people in through an organization's OIDC providers. Start
// stores a Request, bound to a new RequestCookie value by its SHA-256, and
// answers the authorization request: a PKCE S256 challenge, a nonce,
// Scopes, and max_age=0 with prompt=login for a Fresh purpose. A sign-in
// needs the provider enabled, an enable an organization admin's browser
// session, a re-authentication a member's; the kind's feature must be in
// the organization's tier; return_to must be a path (CheckReturnTo).
// Callback consumes the request once, within RequestTTL, for the browser
// holding the cookie, redeems the code through RelyingParty, and checks
// the ID token beyond the relying party's checks (CheckIDToken: the nonce,
// a non-empty sub, azp for several audiences, auth_time within Skew for a
// Fresh purpose). Settings.Identity maps the claims: the subject from the
// mapping's subject claim, a verified email only, the groups as strings
// unless _claim_names replaced them, and sid. ResolveMember decides the
// member: the identity's, refused when deactivated; else the one pending
// member invited under the login; else a new one. The store writes the
// member and a WEB session of actor kind user in no account, replacing the
// member's live one, with the groups as its original teams. LogoutURL is
// the provider's end-session URL for a session, and BackchannelLogout ends
// the sessions a verified logout token names, accepting each jti once.
//
// ref: decisions 0006 and 0021
//
// # Input and output
//
// None of its own: Service and SignIn read and write through their stores,
// check features through featuresapi.Options, and reach a provider only
// through RelyingParty and Discovery. NewSigningKey and SignIn's states, nonces and
// cookie values read crypto/rand, and kernel.NewULID the clock and
// crypto/rand.
//
// # Dependencies
//
// It imports the standard library, golang.org/x/oauth2, internal/kernel,
// internal/features/api, internal/platform/crypt, the access domain's api
// package and its member, orgadmin, organization, port and session
// packages. The access domain's HTTP adapter, pg adapter, OIDC adapter and
// assembly use it.
