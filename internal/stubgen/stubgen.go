// Package stubgen writes UnimplementedStrict, a type that implements a
// generated StrictServerInterface by answering 501 for every operation.
// oapi-codegen emits an unimplemented type for the plain ServerInterface but
// not for the strict one, and the strict one is what the server implements;
// without the stub every scaffolded operation would need a hand-written
// stub before the tree compiles.
package stubgen

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// InterfaceName is the strict interface oapi-codegen generates.
const InterfaceName = "StrictServerInterface"

// TypeName is the stub type written into the generated package.
const TypeName = "UnimplementedStrict"

// OutputName is the stub file, next to server.gen.go.
const OutputName = "unimplemented.gen.go"

// ProblemImport is the package whose NotImplementedError the stubs return;
// its ResponseError renders it as a 501 problem.
const ProblemImport = "github.com/weaveplatform/infraweave/internal/server/problem"

var (
	ErrNoInterface = errors.New("stubgen: " + InterfaceName + " not found")
	ErrNoRoute     = errors.New("stubgen: method has no (METHOD /path) comment")
	ErrNoOperation = errors.New("stubgen: route has no operationId in the spec")
)

// Method is one strict interface method and the operation it serves.
type Method struct {
	Name     string
	Request  string
	Response string
	// Route is "METHOD /path", from the comment oapi-codegen writes above
	// each method.
	Route string
	// OperationID is the spec's operationId for Route.
	OperationID string
}

// routeComment matches oapi-codegen's "// (GET /stacks)" method comment.
var routeComment = regexp.MustCompile(`^\(([A-Z]+) (/\S*)\)$`)

// Parse extracts the package name and the strict interface methods from
// generated server source.
func Parse(src []byte) (string, []Method, error) {
	f, err := parser.ParseFile(token.NewFileSet(), "server.gen.go", src, parser.ParseComments)
	if err != nil {
		return "", nil, fmt.Errorf("stubgen: parse: %w", err)
	}
	it := findInterface(f)
	if it == nil {
		return "", nil, ErrNoInterface
	}
	methods := make([]Method, 0, len(it.Methods.List))
	for _, m := range it.Methods.List {
		ft, ok := m.Type.(*ast.FuncType)
		if !ok || len(m.Names) == 0 {
			continue
		}
		route := ""
		if m.Doc != nil {
			for _, c := range m.Doc.List {
				if g := routeComment.FindStringSubmatch(
					strings.TrimSpace(strings.TrimPrefix(c.Text, "//")),
				); g != nil {
					route = g[1] + " " + g[2]
				}
			}
		}
		if route == "" {
			return "", nil, fmt.Errorf("%w: %s", ErrNoRoute, m.Names[0].Name)
		}
		methods = append(methods, Method{
			Name:     m.Names[0].Name,
			Request:  typeString(ft.Params.List[len(ft.Params.List)-1].Type),
			Response: typeString(ft.Results.List[0].Type),
			Route:    route,
		})
	}
	return f.Name.Name, methods, nil
}

func findInterface(f *ast.File) *ast.InterfaceType {
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			if ts, ok := spec.(*ast.TypeSpec); ok && ts.Name.Name == InterfaceName {
				if it, ok := ts.Type.(*ast.InterfaceType); ok {
					return it
				}
			}
		}
	}
	return nil
}

func typeString(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		return typeString(t.X) + "." + t.Sel.Name
	case *ast.StarExpr:
		return "*" + typeString(t.X)
	default:
		return "any"
	}
}

// Generate renders the stub file. Every method returns a
// problem.NotImplementedError naming its operationId and route.
func Generate(pkg string, methods []Method) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/stubgen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	// A spec whose paths are still empty yields an interface with no
	// methods, and the file must not import packages it doesn't use.
	if len(methods) > 0 {
		fmt.Fprintf(&b, "import (\n\t\"context\"\n\n\t%q\n)\n\n", ProblemImport)
	}
	fmt.Fprintf(&b, "// %s answers 501 for every operation. The server embeds it and\n", TypeName)
	b.WriteString("// overrides the operations a family implements.\n")
	fmt.Fprintf(&b, "type %s struct{}\n\n", TypeName)
	fmt.Fprintf(&b, "var _ %s = %s{}\n\n", InterfaceName, TypeName)
	for _, m := range methods {
		fmt.Fprintf(
			&b,
			"func (%s) %s(context.Context, %s) (%s, error) {\n",
			TypeName,
			m.Name,
			m.Request,
			m.Response,
		)
		fmt.Fprintf(
			&b,
			"\treturn nil, &problem.NotImplementedError{OperationID: %q, Route: %q}\n}\n\n",
			m.OperationID,
			m.Route,
		)
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("stubgen: format: %w", err)
	}
	return out, nil
}

// Run reads the generated server at genPath and the spec it came from, and
// writes the stub next to the server. It returns the number of operations
// stubbed.
func Run(genPath, specPath string) (int, error) {
	src, err := os.ReadFile(genPath)
	if err != nil {
		return 0, fmt.Errorf("stubgen: %w", err)
	}
	spec, err := os.ReadFile(specPath)
	if err != nil {
		return 0, fmt.Errorf("stubgen: %w", err)
	}
	pkg, methods, err := Parse(src)
	if err != nil {
		return 0, err
	}
	ids, err := OperationIDs(spec)
	if err != nil {
		return 0, err
	}
	for i := range methods {
		id, ok := ids[methods[i].Route]
		if !ok {
			return 0, fmt.Errorf("%w: %s", ErrNoOperation, methods[i].Route)
		}
		methods[i].OperationID = id
	}
	out, err := Generate(pkg, methods)
	if err != nil {
		return 0, err
	}
	target := filepath.Join(filepath.Dir(genPath), OutputName)
	// Git records no permission bits beyond the executable one, so 0600
	// costs nothing and keeps gosec's rule unexcepted.
	if err := os.WriteFile(target, out, 0o600); err != nil {
		return 0, fmt.Errorf("stubgen: %w", err)
	}
	return len(methods), nil
}
