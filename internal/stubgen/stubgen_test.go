package stubgen

import (
	"errors"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// fixture is the slice of oapi-codegen output stubgen reads: the strict
// interface, with the route comment above each method.
const fixture = `package widgets

import "context"

type StrictServerInterface interface {
	// ListWidgets List widgets
	// (GET /widgets)
	ListWidgets(ctx context.Context, request ListWidgetsRequestObject) (ListWidgetsResponseObject, error)
	// WidgetCreate Create a widget
	// (POST /widgets)
	WidgetCreate(ctx context.Context, request WidgetCreateRequestObject) (*WidgetCreateResponse, error)
}

type Other interface{ Ignored() }
`

const spec = `paths:
  /widgets:
    parameters:
      - {name: x, in: query}
    summary: not an operation
    get: {operationId: widgets}
    post: {operationId: widgetCreate}
`

func TestUnitParse(t *testing.T) {
	pkg, methods, err := Parse([]byte(fixture))
	if err != nil {
		t.Fatal(err)
	}
	want := []Method{
		{
			Name:     "ListWidgets",
			Request:  "ListWidgetsRequestObject",
			Response: "ListWidgetsResponseObject",
			Route:    "GET /widgets",
		},
		{
			Name:     "WidgetCreate",
			Request:  "WidgetCreateRequestObject",
			Response: "*WidgetCreateResponse",
			Route:    "POST /widgets",
		},
	}
	if pkg != "widgets" || len(methods) != len(want) {
		t.Fatalf("pkg %q methods %+v", pkg, methods)
	}
	for i := range want {
		if methods[i] != want[i] {
			t.Errorf("method %d = %+v, want %+v", i, methods[i], want[i])
		}
	}
}

func TestUnitParseErrors(t *testing.T) {
	for name, src := range map[string]string{
		"not Go":       "package",
		"no interface": "package widgets\n\ntype StrictServerInterface struct{}\n",
		"no route":     "package widgets\n\ntype StrictServerInterface interface {\n\t// Lonely\n\tLonely()\n}\n",
	} {
		if _, _, err := Parse([]byte(src)); err == nil {
			t.Errorf("%s: want error", name)
		}
	}
	src := "package widgets\n\ntype StrictServerInterface interface {\n\tBare()\n}\n"
	if _, _, err := Parse([]byte(src)); !errors.Is(err, ErrNoRoute) {
		t.Errorf("method without comment: %v", err)
	}
}

func TestUnitTypeString(t *testing.T) {
	src := "package p\n\nimport \"context\"\n\ntype StrictServerInterface interface {\n" +
		"\t// (GET /a)\n\tA(ctx context.Context, r pkg.Req) (map[string]int, error)\n}\n"
	_, methods, err := Parse([]byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if methods[0].Request != "pkg.Req" || methods[0].Response != "any" {
		t.Errorf("%+v", methods[0])
	}
}

func TestUnitGenerate(t *testing.T) {
	out, err := Generate("widgets", []Method{
		{
			Name:        "ListWidgets",
			Request:     "ListWidgetsRequestObject",
			Response:    "ListWidgetsResponseObject",
			Route:       "GET /widgets",
			OperationID: "widgets",
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"// Code generated by tools/stubgen. DO NOT EDIT.",
		"var _ StrictServerInterface = UnimplementedStrict{}",
		`return nil, &problem.NotImplementedError{OperationID: "widgets", Route: "GET /widgets"}`,
		`"` + ProblemImport + `"`,
	} {
		if !strings.Contains(string(out), want) {
			t.Errorf("stub lacks %s:\n%s", want, out)
		}
	}
	empty, err := Generate("widgets", nil)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(empty), "import") {
		t.Errorf("an empty interface must import nothing:\n%s", empty)
	}
	if _, err := Generate("not a package", nil); err == nil {
		t.Error("unformattable output: want error")
	}
}

func TestUnitOperationIDs(t *testing.T) {
	ids, err := OperationIDs([]byte(spec))
	if err != nil {
		t.Fatal(err)
	}
	if len(ids) != 2 || ids["GET /widgets"] != "widgets" || ids["POST /widgets"] != "widgetCreate" {
		t.Errorf("ids = %v", ids)
	}
	if _, err := OperationIDs([]byte("paths: [")); err == nil {
		t.Error("malformed spec: want error")
	}
	if _, err := OperationIDs([]byte("paths:\n  /a:\n    get: [1]\n")); err == nil {
		t.Error("operation that isn't a mapping: want error")
	}
}

func TestUnitRun(t *testing.T) {
	dir := t.TempDir()
	gen := filepath.Join(dir, "server.gen.go")
	specPath := filepath.Join(dir, "spec.yaml")
	write := func(path, body string) {
		t.Helper()
		if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write(gen, fixture)
	write(specPath, spec)
	n, err := Run(gen, specPath)
	if err != nil || n != 2 {
		t.Fatalf("Run = %d, %v", n, err)
	}
	out, err := os.ReadFile(filepath.Join(dir, OutputName))
	if err != nil || !strings.Contains(string(out), `OperationID: "widgetCreate"`) {
		t.Fatalf("stub not written: %v\n%s", err, out)
	}

	if _, err := Run(filepath.Join(dir, "missing.go"), specPath); err == nil {
		t.Error("missing server: want error")
	}
	if _, err := Run(gen, filepath.Join(dir, "missing.yaml")); err == nil {
		t.Error("missing spec: want error")
	}
	write(specPath, "paths: [")
	if _, err := Run(gen, specPath); err == nil {
		t.Error("malformed spec: want error")
	}
	write(specPath, "paths:\n  /widgets:\n    get: {operationId: widgets}\n")
	if _, err := Run(
		gen,
		specPath,
	); !errors.Is(err, ErrNoOperation) ||
		!strings.Contains(err.Error(), "POST /widgets") {
		t.Errorf("route missing from spec: %v", err)
	}
	write(gen, "package")
	if _, err := Run(gen, specPath); err == nil {
		t.Error("malformed server: want error")
	}
	write(gen, "package bad name\n\ntype StrictServerInterface interface{}\n")
	if _, err := Run(gen, specPath); err == nil {
		t.Error("unparseable package: want error")
	}
}
