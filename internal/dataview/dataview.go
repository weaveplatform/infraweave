// Package dataview renders docs/implementation/tiers.md, the view of the
// docs/data registers that readers want as tables: every feature of the
// catalogue against the five seeded tiers, the seeded limits, and how many
// reference rows each phase of the plan owns. The registers are the only
// copy of that data, so the view is generated (make generate) and drift is
// caught by make verify-generate rather than by review.
package dataview

import (
	"bytes"
	"cmp"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

// Register files under the data directory, and the view's place relative to
// them; links in register text start from the data directory, so the view
// rewrites them for its own directory.
const (
	FeaturesFile     = "features.json"
	CapabilitiesFile = "capabilities.json"
	// fromView is the data directory as the view, in docs/implementation,
	// reaches it.
	fromView = "../data/"
)

var (
	ErrUnknownTier = errors.New("dataview: unknown lowest seeded tier")
	ErrNoPhase     = errors.New("dataview: capability record has no phase")
)

// tier is a seeded tier: its name in the catalogue and its key in a limit's
// values. The order is the order of the matrix columns.
type tier struct {
	name, key string
}

var tiers = []tier{
	{"Free", "free"},
	{"Starter", "starter"},
	{"Starter+", "starterPlus"},
	{"Business", "business"},
	{"Enterprise", "enterprise"},
}

type feature struct {
	ID         string         `json:"id"`
	Kind       string         `json:"kind"`
	Gates      string         `json:"gates"`
	Field      string         `json:"field"`
	Unit       string         `json:"unit"`
	LowestTier string         `json:"lowestTier"`
	Values     map[string]int `json:"values"`
	Phase      string         `json:"phase"`
}

type capability struct {
	ID         string `json:"id"`
	Kind       string `json:"kind"`
	Infraweave struct {
		Phase    string `json:"phase"`
		APIPhase string `json:"apiPhase"`
	} `json:"infraweave"`
}

// summaryKinds are the capability kinds the phase summary counts, in its
// column order. Untagged operations are left out: the reference counts them
// under no tag, and the summary counts the reference's rows.
var summaryKinds = []struct{ kind, heading string }{
	{"tag", "Tags"},
	{"resource", "Resources (API)"},
	{"data-source", "Data sources (API)"},
	{"tier-feature", "`BillingTierFeature` values"},
}

// Write renders the view of the registers in dataDir to out.
func Write(dataDir, out string) error {
	f, err := os.ReadFile(filepath.Join(dataDir, FeaturesFile))
	if err != nil {
		return fmt.Errorf("dataview: %w", err)
	}
	c, err := os.ReadFile(filepath.Join(dataDir, CapabilitiesFile))
	if err != nil {
		return fmt.Errorf("dataview: %w", err)
	}
	b, err := Render(f, c)
	if err != nil {
		return err
	}
	if err := os.WriteFile(out, b, 0o600); err != nil {
		return fmt.Errorf("dataview: %w", err)
	}
	return nil
}

// Render returns the view of the two registers, given their contents.
func Render(featuresJSON, capabilitiesJSON []byte) ([]byte, error) {
	var fs struct {
		Records []feature `json:"records"`
	}
	if err := json.Unmarshal(featuresJSON, &fs); err != nil {
		return nil, fmt.Errorf("dataview: %s: %w", FeaturesFile, err)
	}
	var cs struct {
		Records []capability `json:"records"`
	}
	if err := json.Unmarshal(capabilitiesJSON, &cs); err != nil {
		return nil, fmt.Errorf("dataview: %s: %w", CapabilitiesFile, err)
	}
	var b bytes.Buffer
	b.WriteString("# Seeded tiers\n\n")
	b.WriteString(
		"Generated by `make generate` from [`docs/data/features.json`](" + fromView + FeaturesFile +
			") and [`capabilities.json`](" + fromView + CapabilitiesFile + "); not edited by hand.\n",
	)
	b.WriteString("The [capability roadmap](capability-roadmap.md) explains how to read it.\n")
	if err := matrix(&b, fs.Records); err != nil {
		return nil, err
	}
	limits(&b, fs.Records)
	if err := summary(&b, cs.Records); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

func tierIndex(name string) int {
	return slices.IndexFunc(tiers, func(t tier) bool { return t.name == name })
}

// matrix writes every capability and option against the tiers, ordered by
// lowest seeded tier and then by name, so each tier's additions read as one
// block.
func matrix(b *bytes.Buffer, all []feature) error {
	type row struct {
		f   feature
		low int
	}
	var rows []row
	for _, f := range all {
		if f.Kind != "capability" && f.Kind != "option" {
			continue
		}
		low := tierIndex(f.LowestTier)
		if low < 0 {
			return fmt.Errorf("%w: %s has %q", ErrUnknownTier, f.ID, f.LowestTier)
		}
		rows = append(rows, row{f, low})
	}
	slices.SortFunc(
		rows,
		func(x, y row) int { return cmp.Or(cmp.Compare(x.low, y.low), cmp.Compare(x.f.ID, y.f.ID)) },
	)
	b.WriteString("\n## Features by lowest seeded tier\n\n")
	b.WriteString("A feature is in its lowest seeded tier and every tier above it.\n\n")
	b.WriteString("| Feature | Kind | Gates |")
	for _, t := range tiers {
		b.WriteString(" " + t.name + " |")
	}
	b.WriteString(" Phase |\n|---|---|---|")
	b.WriteString(strings.Repeat("---|", len(tiers)+1) + "\n")
	for _, r := range rows {
		gates := cmp.Or(r.f.Gates, r.f.Field)
		fmt.Fprintf(b, "| `%s` | %s | %s |", r.f.ID, r.f.Kind, cell(gates))
		for i := range tiers {
			if i >= r.low {
				b.WriteString(" ✓ |")
			} else {
				b.WriteString(" |")
			}
		}
		fmt.Fprintf(b, " %s |\n", r.f.Phase)
	}
	return nil
}

// limits writes each limit's value per tier; an empty cell is no limit.
func limits(b *bytes.Buffer, all []feature) {
	b.WriteString("\n## Seeded limits\n\n")
	b.WriteString(
		"Every limit is pooled across an organization's accounts. An empty cell means no limit.\n\n",
	)
	b.WriteString("| Limit | Unit |")
	for _, t := range tiers {
		b.WriteString(" " + t.name + " |")
	}
	b.WriteString(" Phase |\n|---|---|" + strings.Repeat("---|", len(tiers)+1) + "\n")
	for _, f := range all {
		if f.Kind != "limit" {
			continue
		}
		fmt.Fprintf(b, "| `%s` | %s |", f.ID, cell(f.Unit))
		for _, t := range tiers {
			if v, ok := f.Values[t.key]; ok {
				b.WriteString(" " + strconv.Itoa(v) + " |")
			} else {
				b.WriteString(" |")
			}
		}
		fmt.Fprintf(b, " %s |\n", f.Phase)
	}
}

var phaseName = regexp.MustCompile(`^P(\d+)([a-z]?)$`)

// phaseOrder sorts phases as the plan numbers them, P3 before P3b before
// P10, and anything else after them.
func phaseOrder(a, b string) int {
	key := func(p string) (int, string) {
		m := phaseName.FindStringSubmatch(p)
		if m == nil {
			return 1 << 30, p
		}
		n, _ := strconv.Atoi(m[1])
		return n, m[2]
	}
	an, as := key(a)
	bn, bs := key(b)
	return cmp.Or(cmp.Compare(an, bn), cmp.Compare(as, bs))
}

// superseded is the summary row for rows no phase builds.
const superseded = "Superseded"

// summary counts the reference rows each phase owns: a tag or value by its
// phase, a Terraform row by its API phase.
func summary(b *bytes.Buffer, all []capability) error {
	counts := map[string][]int{}
	total := make([]int, len(summaryKinds))
	for _, c := range all {
		col := slices.IndexFunc(
			summaryKinds,
			func(k struct{ kind, heading string }) bool { return k.kind == c.Kind },
		)
		if col < 0 {
			continue
		}
		p := cmp.Or(c.Infraweave.Phase, c.Infraweave.APIPhase)
		switch p {
		case "":
			return fmt.Errorf("%w: %s", ErrNoPhase, c.ID)
		case "none":
			p = superseded
		}
		if counts[p] == nil {
			counts[p] = make([]int, len(summaryKinds))
		}
		counts[p][col]++
		total[col]++
	}
	phases := make([]string, 0, len(counts))
	for p := range counts {
		phases = append(phases, p)
	}
	slices.SortFunc(phases, phaseOrder)
	b.WriteString("\n## Summary by phase\n\n")
	b.WriteString(
		"Counts of the reference rows each phase owns. Superseded counts the rows no phase builds.\n\n",
	)
	b.WriteString("| Phase |")
	for _, k := range summaryKinds {
		b.WriteString(" " + k.heading + " |")
	}
	b.WriteString("\n|---|" + strings.Repeat("---|", len(summaryKinds)) + "\n")
	line := func(name string, n []int) {
		b.WriteString("| " + name + " |")
		for _, v := range n {
			b.WriteString(" " + strconv.Itoa(v) + " |")
		}
		b.WriteString("\n")
	}
	for _, p := range phases {
		line(p, counts[p])
	}
	line("Total", total)
	return nil
}

var link = regexp.MustCompile(`\]\(([^)\s]+)\)`)

// cell makes register markdown fit a table cell of the view: a pipe would
// end the cell, and a relative link starts from docs/data, not from the
// view's directory.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return link.ReplaceAllStringFunc(s, func(m string) string {
		t := link.FindStringSubmatch(m)[1]
		if strings.Contains(t, ":") || strings.HasPrefix(t, "#") {
			return m
		}
		return "](" + path.Clean(fromView+t) + ")"
	})
}
