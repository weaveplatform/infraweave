const catalogueFeatures = `{"records": [
  {"id": "stacks", "kind": "capability", "lowestTier": "Free", "phase": "P5"},
  {"id": "drift", "kind": "capability", "lowestTier": "Starter+", "requires": ["pools"], "phase": "P16"},
  {"id": "pools", "kind": "capability", "lowestTier": "Starter+", "phase": "P9"},
  {"id": "seats", "kind": "limit", "values": {"free": 2, "starterPlus": 10}, "phase": "P3b"},
  {"id": "billing", "kind": "switch", "phase": "P3b"}
]}`

const catalogueCapabilities = `{"records": [
  {"id": "tag:Stacks", "kind": "tag", "infraweave": {"phase": "P5"}},
  {"id": "tier-feature:DRIFT_DETECTION", "kind": "tier-feature", "infraweave": {"feature": "` + "`drift`" + `"}},
  {"id": "tier-feature:PRIVATE_WORKERS", "kind": "tier-feature", "infraweave": {"feature": "` + "`pools` and `drift`: both, as `stacks` notes" + `"}},
  {"id": "tier-feature:SSO", "kind": "tier-feature", "infraweave": {"feature": "none: superseded"}}
]}`

const wantCatalogue = `// Code generated by tools/dataview from docs/data/features.json and capabilities.json. DO NOT EDIT.

package features

var catalogue = []Feature{
	{Name: "billing", Kind: "switch", Phase: "P3b"},
	{Name: "drift", Kind: "capability", Phase: "P16", LowestTier: "Starter+", Requires: []string{"pools"}, TierFeatures: []string{"DRIFT_DETECTION", "PRIVATE_WORKERS"}},
	{Name: "pools", Kind: "capability", Phase: "P9", LowestTier: "Starter+", TierFeatures: []string{"PRIVATE_WORKERS"}},
	{Name: "seats", Kind: "limit", Phase: "P3b", Values: map[string]int64{"Free": 2, "Starter+": 10}},
	{Name: "stacks", Kind: "capability", Phase: "P5", LowestTier: "Free"},
}
`

func TestUnitCatalogue(t *testing.T) {
	got, err := Catalogue([]byte(catalogueFeatures), []byte(catalogueCapabilities))
	if err != nil {
		t.Fatal(err)
	}
	if d := cmp.Diff(wantCatalogue, string(got)); d != "" {
		t.Errorf("catalogue (-want +got):\n%s", d)
	}
}

func TestUnitCatalogueErrors(t *testing.T) {
	record := func(r string) []byte { return []byte(`{"records": [` + r + `]}`) }
	empty := record("")
	for _, c := range []struct {
		name         string
		features     []byte
		capabilities []byte
		want         error
	}{
		{"features not JSON", []byte("["), empty, nil},
		{"capabilities not JSON", empty, []byte("["), nil},
		{
			"an unknown lowest tier",
			record(`{"id": "x", "kind": "capability", "lowestTier": "Gold"}`), empty, ErrUnknownTier,
		},
		{
			"an unknown requirement",
			record(`{"id": "x", "kind": "capability", "lowestTier": "Free", "requires": ["y"]}`), empty,
			ErrUnknownRequirement,
		},
		{
			"an unknown covering feature",
			empty, record(`{"id": "tier-feature:X", "kind": "tier-feature", "infraweave": {"feature": "` + "`x`" + `"}}`),
			ErrUnknownTierFeature,
		},
	} {
		t.Run(c.name, func(t *testing.T) {
			_, err := Catalogue(c.features, c.capabilities)
			if err == nil || c.want != nil && !errors.Is(err, c.want) {
				t.Errorf("Catalogue = %v, want %v", err, c.want)
			}
		})
	}
}

func TestUnitWriteCatalogue(t *testing.T) {
	dir := t.TempDir()
	out := filepath.Join(dir, "catalogue.gen.go")
	if err := WriteCatalogue(dir, out); err == nil {
		t.Error("no error without features.json")
	}
	mustWrite(t, filepath.Join(dir, FeaturesFile), catalogueFeatures)
	if err := WriteCatalogue(dir, out); err == nil {
		t.Error("no error without capabilities.json")
	}
	mustWrite(t, filepath.Join(dir, CapabilitiesFile), "[")
	if err := WriteCatalogue(dir, out); err == nil {
		t.Error("no error with capabilities.json not JSON")
	}
	mustWrite(t, filepath.Join(dir, CapabilitiesFile), catalogueCapabilities)
	if err := WriteCatalogue(dir, filepath.Join(dir, "missing", "catalogue.gen.go")); err == nil {
		t.Error("no error writing into a missing directory")
	}
	if err := WriteCatalogue(dir, out); err != nil {
		t.Fatal(err)
	}
	if b, err := os.ReadFile(out); err != nil || string(b) != wantCatalogue {
		t.Errorf("wrote %q, %v", b, err)
	}
}

// TestUnitCommittedCatalogue fails when the compiled-in catalogue is not
// what the committed registers generate, so go test catches a register
// edit made without make generate.
func TestUnitCommittedCatalogue(t *testing.T) {
	root := filepath.Join("..", "..", "..")
	f, err := os.ReadFile(filepath.Join(root, "docs", "data", FeaturesFile))
	if err != nil {
		t.Fatal(err)
	}
	c, err := os.ReadFile(filepath.Join(root, "docs", "data", CapabilitiesFile))
	if err != nil {
		t.Fatal(err)
	}
	got, err := Catalogue(f, c)
	if err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile(filepath.Join(root, "internal", "features", "catalogue.gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	text := strings.ReplaceAll(string(committed), "\r\n", "\n")
	if d := cmp.Diff(text, string(got)); d != "" {
		t.Errorf(
			"internal/features/catalogue.gen.go is stale; run make generate (-committed +generated):\n%s",
			d,
		)
	}
}
