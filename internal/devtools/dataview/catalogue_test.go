const wantCatalogue = `// Code generated by tools/dataview from docs/data/features.json and capabilities.json. DO NOT EDIT.

package features

var catalogue = []Feature{
	{Name: "aggregated", Kind: "option", LowestTier: "Business", Preview: &Preview{Name: "Aggregated checks", Description: "One ` + "`" + `\"check\"` + "`" + ` per commit.", DocsURL: "https://docs.example.com/checks", ImageURL: "https://docs.example.com/checks.png"}},
	{Name: "billing", Kind: "switch"},
	{Name: "drift", Kind: "capability", LowestTier: "Business", Requires: []string{"pools"}, TierFeatures: []string{"DRIFT_DETECTION", "PRIVATE_WORKERS"}, Preview: &Preview{Name: "Drift detection", Description: "Finds resources that changed outside a run.", DocsURL: "https://docs.example.com/drift"}},
	{Name: "pools", Kind: "capability", LowestTier: "Business", TierFeatures: []string{"PRIVATE_WORKERS"}},
	{Name: "seats", Kind: "limit", Values: map[string]int64{"Free": 2, "Business": 10}},
	{Name: "stacks", Kind: "capability", LowestTier: "Free"},
}
`

func TestUnitCatalogue(t *testing.T) {
	got, err := Catalogue([]byte(documentFixture(t, "catalogue-features.json")), []byte(documentFixture(t, "catalogue-capabilities.json")))
	if err != nil {
		t.Fatal(err)
	}
	if d := cmp.Diff(wantCatalogue, string(got)); d != "" {
		t.Errorf("catalogue (-want +got):\n%s", d)
	}
}

func TestUnitCatalogueErrors(t *testing.T) {
	record := func(r string) []byte { return []byte(`{"records": [` + r + `]}`) }
	empty := record("")
	const marker = `{"name": "X", "description": "Does x.", "docsUrl": "https://docs.example.com/x"}`
	for _, c := range []struct {
		name         string
		features     []byte
		capabilities []byte
		want         error
	}{
		{"features not JSON", []byte("["), empty, nil},
		{"capabilities not JSON", empty, []byte("["), nil},
		{
			"an unknown lowest tier",
			record(`{"id": "x", "kind": "capability", "lowestTier": "Gold"}`), empty, ErrUnknownTier,
		},
		{
			"an unknown limit tier",
			record(`{"id":"seats","kind":"limit","values":{"gold":2}}`), empty, ErrUnknownTier,
		},
		{
			"an unknown requirement",
			record(`{"id": "x", "kind": "capability", "lowestTier": "Free", "requires": ["y"]}`), empty,
			ErrUnknownRequirement,
		},
		{
			"a preview on a limit",
			record(`{"id": "seats", "kind": "limit", "values": {"free": 2}, "preview": ` + marker + `}`), empty,
			ErrInvalidPreview,
		},
		{
			"a preview on the switch",
			record(`{"id": "billing", "kind": "switch", "preview": ` + marker + `}`), empty, ErrInvalidPreview,
		},
		{
			"a preview without its name",
			record(`{"id": "x", "kind": "capability", "lowestTier": "Free", "preview": ` +
				strings.Replace(marker, `"X"`, `""`, 1) + `}`), empty, ErrInvalidPreview,
		},
		{
			"a preview without its description",
			record(`{"id": "x", "kind": "option", "lowestTier": "Free", "preview": ` +
				strings.Replace(marker, `"Does x."`, `""`, 1) + `}`), empty, ErrInvalidPreview,
		},
		{
			"a preview without its docsUrl",
			record(`{"id": "x", "kind": "capability", "lowestTier": "Free", "preview": {"name": "X", "description": "Does x."}}`),
			empty, ErrInvalidPreview,
		},
		{
			"a preview with an http docsUrl",
			record(`{"id": "x", "kind": "capability", "lowestTier": "Free", "preview": ` +
				strings.Replace(marker, `"https://docs.example.com/x"`, `"http://docs.example.com/x"`, 1) + `}`),
			empty, ErrInvalidPreview,
		},
		{
			"a preview with an http imageUrl",
			record(`{"id": "x", "kind": "capability", "lowestTier": "Free", "preview": ` +
				strings.Replace(marker, `}`, `, "imageUrl": "http://docs.example.com/x.png"}`, 1) + `}`),
			empty, ErrInvalidPreview,
		},
		{
			"a preview with a docsUrl that is no URL",
			record(`{"id": "x", "kind": "capability", "lowestTier": "Free", "preview": ` +
				strings.Replace(marker, `"https://docs.example.com/x"`, `"https://%zz"`, 1) + `}`),
			empty, ErrInvalidPreview,
		},
		{
			"an unknown covering feature",
			empty, record(`{"id": "tier-feature:X", "kind": "tier-feature", "infraweave": {"feature": "` + "`x`" + `"}}`),
			ErrUnknownTierFeature,
		},
	} {
		t.Run(c.name, func(t *testing.T) {
			_, err := Catalogue(c.features, c.capabilities)
			if err == nil || c.want != nil && !errors.Is(err, c.want) {
				t.Errorf("Catalogue = %v, want %v", err, c.want)
			}
		})
	}
}

func TestUnitWriteCatalogue(t *testing.T) {
	dir := t.TempDir()
	out := filepath.Join(dir, "catalogue.gen.go")
	if err := WriteCatalogue(dir, out); err == nil {
		t.Error("no error without features.json")
	}
	mustWrite(t, filepath.Join(dir, FeaturesFile), documentFixture(t, "catalogue-features.json"))
	if err := WriteCatalogue(dir, out); err == nil {
		t.Error("no error without capabilities.json")
	}
	mustWrite(t, filepath.Join(dir, CapabilitiesFile), "[")
	if err := WriteCatalogue(dir, out); err == nil {
		t.Error("no error with capabilities.json not JSON")
	}
	mustWrite(t, filepath.Join(dir, CapabilitiesFile), documentFixture(t, "catalogue-capabilities.json"))
	if err := WriteCatalogue(dir, filepath.Join(dir, "missing", "catalogue.gen.go")); err == nil {
		t.Error("no error writing into a missing directory")
	}
	if err := WriteCatalogue(dir, out); err != nil {
		t.Fatal(err)
	}
	if b, err := os.ReadFile(out); err != nil || string(b) != wantCatalogue {
		t.Errorf("wrote %q, %v", b, err)
	}
}

// TestUnitCommittedCatalogue fails when the compiled-in catalogue is not
// what the committed registers generate, so go test catches a register
// edit made without make generate.
func TestUnitCommittedCatalogue(t *testing.T) {
	root := filepath.Join("..", "..", "..")
	f, err := os.ReadFile(filepath.Join(root, "docs", "data", FeaturesFile))
	if err != nil {
		t.Fatal(err)
	}
	c, err := os.ReadFile(filepath.Join(root, "docs", "data", CapabilitiesFile))
	if err != nil {
		t.Fatal(err)
	}
	got, err := Catalogue(f, c)
	if err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile(filepath.Join(root, "internal", "features", "catalogue.gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	text := strings.ReplaceAll(string(committed), "\r\n", "\n")
	if d := cmp.Diff(text, string(got)); d != "" {
		t.Errorf(
			"internal/features/catalogue.gen.go is stale; run make generate (-committed +generated):\n%s",
			d,
		)
	}
}
