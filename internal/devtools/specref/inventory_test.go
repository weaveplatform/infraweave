const (
	fileInventory         = "29-data-model-inventory.md"
	fileInventoryRegister = "graphql-inventory.json"
)

func inventoryOutputs(t *testing.T) InventoryOutputs {
	t.Helper()
	dir := t.TempDir()
	return InventoryOutputs{
		Report:   filepath.Join(dir, fileInventory),
		Register: filepath.Join(dir, fileInventoryRegister),
	}
}

func TestUnitInventoryGolden(t *testing.T) {
	dir := writeFixtureDir(t)
	out := inventoryOutputs(t)
	if err := InventoryFile(dir, out); err != nil {
		t.Fatal(err)
	}
	first := map[string][]byte{}
	for name, p := range map[string]string{fileInventory: out.Report, fileInventoryRegister: out.Register} {
		b, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		golden(t, name, b)
		first[p] = b
	}
	if err := CheckInventory(dir, out); err != nil {
		t.Errorf("check right after write: %v", err)
	}
	if err := InventoryFile(dir, out); err != nil {
		t.Fatal(err)
	}
	for p, b := range first {
		if second, err := os.ReadFile(p); err != nil || !bytes.Equal(b, second) {
			t.Errorf("regenerating changed the bytes of %s (err %v)", p, err)
		}
	}
}

// TestUnitInventorySemantics asserts what the report's golden file encodes,
// so a reviewer of an -update diff knows what must still hold.
func TestUnitInventorySemantics(t *testing.T) {
	md := string(Inventory(fixtureSchema(), fixtureLock()))
	for _, want := range []string{
		"# 29: Data model inventory\n",
		"Checked against: the introspection snapshot `abc` (fetched 2026-10-28T06:58:57Z)",
		"Research baseline: **2026-10-28**.",
		"Generated by `make reference-inventory` from `api/reference/spacelift/introspection.json`, together with the register [`graphql-inventory.json`](../../data/graphql-inventory.json); do not edit either.",
		"[28](28-data-model.md)",
		"| Object types | 13 | 68 |",
		"| Unions | 1 | 2 |",
		"| Scalars | 5 | 0 |",
		"\n## Sources\n",
	} {
		if !strings.Contains(md, want) {
			t.Errorf("report lacks %q", want)
		}
	}
	sections := []string{"## Reading the register", "## Summary", "## Sources"}
	last := -1
	for _, s := range sections {
		i := strings.Index(md, "\n"+s+"\n")
		if i <= last {
			t.Errorf("section %q out of order", s)
		}
		last = i
	}
	// The register is the one copy of the types; the report only counts them.
	if strings.Contains(md, "### Stack") || strings.Contains(md, "`latestRun`") {
		t.Error("report lists types the register holds")
	}
}

func decodeRegister(t *testing.T, b []byte) (string, map[string]inventoryType, []string) {
	t.Helper()
	var doc inventoryRegister
	if err := json.Unmarshal(b, &doc); err != nil {
		t.Fatal(err)
	}
	byID := map[string]inventoryType{}
	ids := make([]string, 0, len(doc.Records))
	for _, r := range doc.Records {
		byID[r.ID] = r
		ids = append(ids, r.ID)
	}
	return doc.Schema, byID, ids
}

// TestUnitInventoryRegisterSemantics asserts what the register's golden file
// encodes.
func TestUnitInventoryRegisterSemantics(t *testing.T) {
	b := InventoryRegister(fixtureSchema())
	if !bytes.HasSuffix(b, []byte("}\n")) ||
		!bytes.Contains(b, []byte("\n  \"records\": [\n    {\n      \"id\": ")) {
		t.Errorf("register is not two-space indented with a trailing newline:\n%.200s", b)
	}
	schema, byID, ids := decodeRegister(t, b)
	if schema != RegisterSchema {
		t.Errorf("$schema = %q, want %q", schema, RegisterSchema)
	}
	order := map[string]int{}
	for i, k := range inventoryKinds {
		order[k.kind] = i
	}
	for i := 1; i < len(ids); i++ {
		a, z := byID[ids[i-1]], byID[ids[i]]
		if order[a.Kind] > order[z.Kind] || a.Kind == z.Kind && a.ID >= z.ID {
			t.Errorf("record %s (%s) before %s (%s)", a.ID, a.Kind, z.ID, z.Kind)
		}
	}
	stack := byID["Stack"]
	fields := map[string]inventoryField{}
	for _, f := range stack.Fields {
		fields[f.Name] = f
	}
	if stack.Kind != KindObject || stack.Fields[0].Name != "id" {
		t.Errorf("Stack = %+v, want an object with upstream field order", stack)
	}
	if f := fields["labels"]; f.Type != "[String!]!" || f.Nullable || f.Deprecated {
		t.Errorf("labels = %+v", f)
	}
	if f := fields["runs"]; len(f.Args) != 1 || f.Args[0].Name != "before" ||
		f.Args[0].Type != "String" ||
		!f.Args[0].Nullable {
		t.Errorf("runs = %+v", f)
	}
	if f := fields["latestRun"]; !f.Nullable || f.Type != "Run" {
		t.Errorf("latestRun = %+v", f)
	}
	if f := fields["legacy"]; !f.Deprecated || f.DeprecationReason != "gone" {
		t.Errorf("legacy = %+v", f)
	}
	if u := byID["Owner"]; u.Kind != KindUnion || strings.Join(u.Members, ",") != "User,Team" {
		t.Errorf("Owner = %+v", u)
	}
	if s := byID["String"]; s.Kind != KindScalar || s.Fields != nil || s.Values != nil {
		t.Errorf("String = %+v", s)
	}
	var sawDefault, sawDeprecatedValue bool
	for _, r := range byID {
		for _, f := range r.Fields {
			if r.Kind == KindInputObject && f.Default != nil {
				sawDefault = sawDefault || f.Name == "autodeploy" && *f.Default == "false"
			}
		}
		for _, v := range r.Values {
			sawDeprecatedValue = sawDeprecatedValue ||
				v.Name == "OLD" && v.Deprecated && v.DeprecationReason == "unused"
		}
	}
	if !sawDefault || !sawDeprecatedValue {
		t.Errorf(
			"default autodeploy = false: %v; deprecated OLD: %v",
			sawDefault,
			sawDeprecatedValue,
		)
	}
	if bytes.Contains(b, []byte("The stack name.")) || bytes.Contains(b, []byte("A stack.")) ||
		bytes.Contains(b, []byte("The id field.")) {
		t.Error("register carries upstream descriptions")
	}
}

func TestUnitInventoryEdges(t *testing.T) {
	s := fixtureSchema()
	s.Types = append(s.Types,
		&Type{Kind: KindObject, Name: "__Type", Fields: []Field{field("kind", tString)}},
		&Type{
			Kind:          KindInterface,
			Name:          "Node",
			Fields:        []Field{field("id", nn(tID))},
			PossibleTypes: []TypeRef{obj("Stack")},
		},
	)
	stack := s.Type("Stack")
	stack.Interfaces = []TypeRef{named(KindInterface, "Node")}
	stack.Fields = append(
		stack.Fields,
		deprecated(
			field(
				"old",
				tString,
				InputValue{Name: "first", Type: tInt, DefaultValue: strPtr("10")},
			),
			"  ",
		),
		deprecated(field("html", tString), " Use <a> & <b>.\n"),
	)
	b := InventoryRegister(s)
	if bytes.Contains(b, []byte("__Type")) {
		t.Error("register lists GraphQL's own introspection types")
	}
	if !bytes.Contains(b, []byte(`"deprecationReason": "Use <a> & <b>."`)) {
		t.Error("register escapes HTML or keeps the reason's surrounding space")
	}
	_, byID, _ := decodeRegister(t, b)
	if n := byID["Node"]; n.Kind != KindInterface || strings.Join(n.ImplementedBy, ",") != "Stack" {
		t.Errorf("Node = %+v", n)
	}
	got := byID["Stack"]
	if strings.Join(got.Implements, ",") != "Node" {
		t.Errorf("Stack implements %v", got.Implements)
	}
	for _, f := range got.Fields {
		if f.Name == "old" && (!f.Deprecated || f.DeprecationReason != "" ||
			len(f.Args) != 1 || f.Args[0].Default == nil || *f.Args[0].Default != "10") {
			t.Errorf("old = %+v", f)
		}
	}

	md := string(Inventory(s, nil))
	for _, want := range []string{
		"Checked against: the introspection snapshot `not recorded` (fetched not recorded)",
		"Research baseline: **not recorded**.",
		"| Interfaces | 1 | 1 |",
	} {
		if !strings.Contains(md, want) {
			t.Errorf("report lacks %q", want)
		}
	}
	long := fixtureLock()
	long.Introspection.SHA256 = "b3255fe38f5ef8e08dfaf4fcabc47b12"
	long.Introspection.Endpoint = ""
	md = string(Inventory(fixtureSchema(), long))
	if !strings.Contains(md, "snapshot `b3255fe38f5e`") ||
		!strings.Contains(
			md,
			"introspection of not recorded, sha256 `b3255fe38f5ef8e08dfaf4fcabc47b12`",
		) {
		t.Errorf("long sha: %s", md[:400])
	}
}

func TestUnitInventoryErrors(t *testing.T) {
	dir := writeFixtureDir(t)
	out := inventoryOutputs(t)
	if err := CheckInventory(dir, out); !errors.Is(err, ErrDrift) ||
		!strings.Contains(err.Error(), out.Report) || !strings.Contains(err.Error(), out.Register) {
		t.Errorf("missing files: err = %v, want drift in both", err)
	}
	if err := InventoryFile(dir, out); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(out.Register, []byte("{}\n"), filePerm); err != nil {
		t.Fatal(err)
	}
	if err := CheckInventory(dir, out); !errors.Is(err, ErrDrift) ||
		!strings.Contains(err.Error(), out.Register) || strings.Contains(err.Error(), out.Report) {
		t.Errorf("edited register: err = %v, want drift in %s only", err, out.Register)
	}
	bad := out
	bad.Report = filepath.Join(out.Report, "not-a-dir", "x.md")
	if err := InventoryFile(dir, bad); err == nil {
		t.Error("unwritable report: want error")
	}
	bad = out
	bad.Register = filepath.Join(out.Register, "not-a-dir", "x.json")
	if err := InventoryFile(dir, bad); err == nil {
		t.Error("unwritable register: want error")
	}
	missing := filepath.Join(t.TempDir(), "missing")
	if err := InventoryFile(missing, out); err == nil {
		t.Error("InventoryFile missing dir: want error")
	}
	if err := CheckInventory(missing, out); err == nil || errors.Is(err, ErrDrift) {
		t.Errorf("CheckInventory missing dir: err = %v, want a read error", err)
	}
}
