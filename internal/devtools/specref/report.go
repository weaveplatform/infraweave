package specref

import (
	"fmt"
	"sort"
	"strings"
)

// Report summarises how the upstream surface landed in the reference.
type Report struct {
	Queries, Mutations int
	Styles             map[string]int
	FieldRoutes        int
	RPC                []string
	Excluded           []Excluded
	Overrides          []string
	Terraform          []TFCoverage
	TerraformData      int
	BrunoUnmatched     []string // root fields no Bruno request calls
	DroppedExamples    []string // operations whose Bruno example fails the schema
}

func (b *builder) report() *Report {
	rep := &Report{
		Queries:   len(b.src.Schema.Queries()),
		Mutations: len(b.src.Schema.Mutations()),
		Styles:    map[string]int{},
		Excluded:  b.plan.Excluded,
	}
	for _, r := range b.plan.Routes {
		if r.Style == StyleField {
			rep.FieldRoutes++
			continue
		}
		rep.Styles[r.Style]++
		switch r.Style {
		case StyleRPC:
			rep.RPC = append(rep.RPC, r.Field.Name)
		case StyleOverride:
			rep.Overrides = append(rep.Overrides, r.Field.Name)
		}
		if _, ok := b.bruno[r.Field.Name]; !ok {
			rep.BrunoUnmatched = append(rep.BrunoUnmatched, r.Field.Name)
		}
	}
	if b.tf != nil {
		rep.Terraform = b.tf.coverage
	}
	if b.src.Terraform != nil {
		rep.TerraformData = len(b.src.Terraform.DataSources)
	}
	sort.Strings(rep.RPC)
	sort.Strings(rep.Overrides)
	sort.Strings(rep.BrunoUnmatched)
	sort.Slice(
		rep.Excluded,
		func(i, j int) bool { return rep.Excluded[i].Field < rep.Excluded[j].Field },
	)
	return rep
}

// Markdown renders the report committed as coverage.md.
func (r *Report) Markdown() string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	routed := 0
	for _, n := range r.Styles {
		routed += n
	}
	w("# Spacelift reference coverage\n\n")
	w(
		"Generated by `specref generate`; do not edit. Every root field is either routed or excluded with a reason.\n\n",
	)
	w("| | Count |\n|---|---|\n")
	w(
		"| Root fields (queries + mutations) | %d (%d + %d) |\n",
		r.Queries+r.Mutations,
		r.Queries,
		r.Mutations,
	)
	w("| Routed | %d |\n| Excluded | %d |\n", routed, len(r.Excluded))
	w("| Field routes (resource fields with arguments) | %d |\n", r.FieldRoutes)
	w("| Still RPC-shaped (`POST /<operation-kebab>`) | %d |\n\n", len(r.RPC))

	w("## Routes by rule\n\n| Rule | Routes |\n|---|---|\n")
	for _, s := range sortedKeys(r.Styles) {
		w("| %s | %d |\n", s, r.Styles[s])
	}

	w("\n## Excluded\n\n| Field | Kind | Reason |\n|---|---|---|\n")
	for _, e := range r.Excluded {
		w("| `%s` | %s | %s |\n", e.Field, e.Op, strings.ReplaceAll(e.Reason, "\n", " "))
	}

	w(
		"\n## RPC-shaped mutations\n\nMutations no rule or override places, served as `POST /<operation-kebab>`. Each needs an override in `rest-mapping.yaml`; generation fails once there are more than `rpcBudget`.\n\n",
	)
	for _, f := range r.RPC {
		w("- `%s`\n", f)
	}

	w("\n## Terraform provider coverage\n\n")
	w(
		"Where each resource's attributes land among the inputs of the mutations it calls (%d data sources not mapped). ",
		r.TerraformData,
	)
	w("Nested blocks are listed, not mapped.\n\n")
	w(
		"| Resource | Lands in | Mapped | Unmapped attributes | Terraform-only | Blocks |\n|---|---|---|---|---|---|\n",
	)
	for _, c := range r.Terraform {
		w(
			"| `%s` | %s | %d | %s | %s | %s |\n",
			c.Resource,
			codeList(c.Inputs),
			len(c.Mapped),
			codeList(c.Unmapped),
			codeList(c.TerraformOnly),
			codeList(c.Blocks),
		)
	}

	w(
		"\n## Bruno examples dropped\n\nThese request examples fail the generated JSON schema, so the spec omits them. Known causes: GraphQL input coercion (a single value where a list is expected), and VCS updates that address the default integration by leaving out `customInput`, where REST names every integration by ID in the path.\n\n",
	)
	if len(r.DroppedExamples) == 0 {
		w("None.\n")
	}
	for _, op := range r.DroppedExamples {
		w("- `%s`\n", op)
	}

	w("\n## Root fields no Bruno request calls\n\n")
	if len(r.BrunoUnmatched) == 0 {
		w("None.\n")
	}
	for _, f := range r.BrunoUnmatched {
		w("- `%s`\n", f)
	}
	return b.String()
}

func codeList(items []string) string {
	if len(items) == 0 {
		return "—"
	}
	out := make([]string, len(items))
	for i, s := range items {
		out[i] = "`" + s + "`"
	}
	return strings.Join(out, ", ")
}
