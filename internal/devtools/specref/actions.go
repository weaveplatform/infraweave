package specref

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
)

// Paths of the action catalogue, relative to the repository root.
const (
	ActionCatalogue = "internal/access/api/actions.yaml"
	ActionsGo       = "internal/access/api/actions.gen.go"
)

// ErrActions is an action catalogue that disagrees with the schema's
// Action enum; the error names each value.
var ErrActions = errors.New("specref: action catalogue and Action enum disagree")

// actionEnum is the schema's enum that roles hold.
const actionEnum = "Action"

// disabledAction is the description the schema gives a value roles cannot
// use yet.
const disabledAction = "Disabled. Do not use."

// ActionRow is one row of actions.yaml. Infraweave marks an action of
// infraweave's own, which the enum lacks: an account action on a
// resource that lives in no space, decided on the top space, or, with
// Anywhere, wherever the caller holds it.
type ActionRow struct {
	Subject    string `yaml:"subject"`
	Fallback   string `yaml:"fallback"`
	Disabled   bool   `yaml:"disabled"`
	Deprecated bool   `yaml:"deprecated"`
	Infraweave bool   `yaml:"infraweave"`
	Anywhere   bool   `yaml:"anywhere"`
}

// ParseActionCatalogue reads actions.yaml, rejecting unknown keys.
func ParseActionCatalogue(data []byte) (map[string]ActionRow, error) {
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	rows := map[string]ActionRow{}
	if err := dec.Decode(&rows); err != nil {
		return nil, fmt.Errorf("specref: %s: %w", ActionCatalogue, err)
	}
	return rows, nil
}

// GenerateActions is actions.gen.go for the schema's Action enum and the
// catalogue rows. Each enum value needs a row and each row a value, but an
// infraweave row, which needs none and may not name one, and follows the
// enum's values by name. Every row has a subject and a fallback of
// reader, writer or admin, and an enum value's flags match the schema's:
// disabled for a value it describes as disabled, deprecated for one it
// deprecates. Only an infraweave row is anywhere. Every mismatch is named
// in one ErrActions.
func GenerateActions(s *Schema, rows map[string]ActionRow) ([]byte, error) {
	t := s.Type(actionEnum)
	if t == nil || t.Kind != KindEnum {
		return nil, fmt.Errorf("%w: the schema has no %s enum", ErrActions, actionEnum)
	}
	var problems []string
	seen := map[string]bool{}
	for _, v := range t.EnumValues {
		seen[v.Name] = true
		r, ok := rows[v.Name]
		if !ok {
			problems = append(problems, v.Name+" has no row")
			continue
		}
		problems = append(problems, rowProblems(v.Name, r)...)
		if r.Infraweave {
			problems = append(problems, v.Name+" is infraweave's but in the enum")
		}
		if d := v.Description == disabledAction; r.Disabled != d {
			problems = append(problems, fmt.Sprintf("%s is disabled: %t in the schema", v.Name, d))
		}
		if r.Deprecated != v.IsDeprecated {
			problems = append(problems, fmt.Sprintf("%s is deprecated: %t in the schema",
				v.Name, v.IsDeprecated))
		}
	}
	var stray, own []string
	for name, r := range rows {
		switch {
		case seen[name]:
		case !r.Infraweave:
			stray = append(stray, name+" is not in the enum")
		default:
			own = append(own, name)
			stray = append(stray, rowProblems(name, r)...)
		}
	}
	slices.Sort(stray)
	slices.Sort(own)
	if problems = append(problems, stray...); len(problems) > 0 {
		return nil, fmt.Errorf("%w: %s", ErrActions, strings.Join(problems, "; "))
	}
	names := make([]string, 0, len(t.EnumValues)+len(own))
	for _, v := range t.EnumValues {
		names = append(names, v.Name)
	}
	names = append(names, own...)

	var b bytes.Buffer
	b.WriteString(
		"// Code generated by specref actions from " + Deploy.Dir + "/" + FileIntrospection +
			" and " + ActionCatalogue + "; DO NOT EDIT.\n\npackage api\n\n",
	)
	b.WriteString("// The reference's Action enum, in its order, then infraweave's own " +
		"actions by name.\nconst (\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%s Action = %q\n", actionConst(name), name)
	}
	b.WriteString(
		")\n\n// catalogue is each value's row of actions.yaml.\nvar catalogue = []ActionInfo{\n",
	)
	for _, name := range names {
		r := rows[name]
		fmt.Fprintf(
			&b,
			"\t{Action: %s, Subject: %q, Fallback: Fallback%s, Disabled: %t, Deprecated: %t, "+
				"Infraweave: %t, Anywhere: %t},\n",
			actionConst(name),
			r.Subject,
			upperFirst(r.Fallback),
			r.Disabled,
			r.Deprecated,
			r.Infraweave,
			r.Anywhere,
		)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("specref: format %s: %w", ActionsGo, err)
	}
	return out, nil
}

// rowProblems are what is wrong with name's row whatever the enum says.
func rowProblems(name string, r ActionRow) []string {
	var out []string
	if r.Subject == "" {
		out = append(out, name+" has no subject")
	}
	if !slices.Contains([]string{"reader", "writer", "admin"}, r.Fallback) {
		out = append(out, fmt.Sprintf("%s's fallback %q is not reader, writer or admin",
			name, r.Fallback))
	}
	if r.Anywhere && !r.Infraweave {
		out = append(out, name+" is anywhere but not infraweave's")
	}
	return out
}

// actionConst is the Go name of an enum value: SPACE_ADMIN → ActionSpaceAdmin.
func actionConst(name string) string {
	var b strings.Builder
	b.WriteString("Action")
	for w := range strings.SplitSeq(strings.ToLower(name), "_") {
		b.WriteString(upperFirst(w))
	}
	return b.String()
}

// ActionsFile writes out, actions.gen.go generated from the reference
// directory dir's introspection and the catalogue at catalogue, or with
// check fails with ErrDrift when the committed out differs.
func ActionsFile(dir, catalogue, out string, check bool) error {
	data, err := os.ReadFile(dir + "/" + FileIntrospection)
	if err != nil {
		return fmt.Errorf("specref: %w", err)
	}
	s, err := ParseIntrospection(data)
	if err != nil {
		return err
	}
	if data, err = os.ReadFile(catalogue); err != nil {
		return fmt.Errorf("specref: %w", err)
	}
	rows, err := ParseActionCatalogue(data)
	if err != nil {
		return err
	}
	gen, err := GenerateActions(s, rows)
	if err != nil {
		return err
	}
	if check {
		if got, err := os.ReadFile(out); err != nil || !bytes.Equal(got, gen) {
			return fmt.Errorf("%w: %s (run make generate)", ErrDrift, out)
		}
		return nil
	}
	if err := os.WriteFile(out, gen, filePerm); err != nil {
		return fmt.Errorf("specref: %w", err)
	}
	return nil
}
