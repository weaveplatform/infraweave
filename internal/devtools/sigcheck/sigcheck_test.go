// limit is the repository's: 180 characters, a tab counting 4.
var limit = Limit{MaxLen: 180, TabLen: 4}

// TestUnitReadLimit checks that golines' max-len and tab-len are read
// from a golangci-lint configuration, that golines' defaults stand where
// it names neither, and that a missing or malformed one is an error.
func TestUnitReadLimit(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) string {
		t.Helper()
		path := filepath.Join(dir, name)
		if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
		return path
	}
	for name, c := range map[string]struct {
		body string
		want Limit
	}{
		"both":    {"formatters:\n  settings:\n    golines:\n      max-len: 180\n      tab-len: 8\n", Limit{180, 8}},
		"max-len": {"formatters:\n  settings:\n    golines:\n      max-len: 120\n", Limit{120, 4}},
		"neither": {"version: \"2\"\n", Limit{100, 4}},
	} {
		if got, err := ReadLimit(write(name+".yml", c.body)); err != nil || got != c.want {
			t.Errorf("%s: ReadLimit = %+v, %v, want %+v", name, got, err, c.want)
		}
	}
	if _, err := ReadLimit(filepath.Join(dir, "gone.yml")); !errors.Is(err, ErrConfig) {
		t.Errorf("a missing configuration: %v", err)
	}
	if _, err := ReadLimit(write("bad.yml", "formatters: [")); !errors.Is(err, ErrConfig) {
		t.Errorf("a malformed configuration: %v", err)
	}
	repo, err := ReadLimit(filepath.Join("..", "..", "..", ".golangci.yml"))
	if err != nil || repo != limit {
		t.Errorf("the repository's limit: %+v, %v, want %+v", repo, err, limit)
	}
}

// TestUnitJoin checks the signatures Join joins and the ones it leaves:
// a method's, a function literal's, an interface method's and a bodyless
// declaration's that fit are joined, with no space inside a bracket and
// no trailing comma; one that does not fit, counting a tab as golines
// does, one holding a comment, a string or a struct type, and one already
// on one line are left; trailing comments the joins move are realigned;
// and a generated file is left alone.
func TestUnitJoin(t *testing.T) {
	for name, c := range map[string]struct {
		src, want string
		lines     []int
	}{
		"a method": {
			src:   "package p\n\nfunc (s *S) Get(\n\tctx context.Context,\n\tid string,\n) (\n\tResult,\n\terror,\n) {\n\treturn Result{}, nil\n}\n",
			want:  "package p\n\nfunc (s *S) Get(ctx context.Context, id string) (Result, error) {\n\treturn Result{}, nil\n}\n",
			lines: []int{3},
		},
		"type parameters": {
			src:   "package p\n\nfunc Map[\n\tT any,\n\tU any,\n](\n\tin []T,\n) []U { return nil }\n",
			want:  "package p\n\nfunc Map[T any, U any](in []T) []U { return nil }\n",
			lines: []int{3},
		},
		"a function literal and an interface method": {
			src: "package p\n\ntype API interface {\n\tGet(\n\t\tid string,\n\t) error // gets\n\tPut() error   // puts\n}\n\n" +
				"var f = func(\n\ta int,\n) int {\n\treturn a\n}\n",
			want: "package p\n\ntype API interface {\n\tGet(id string) error // gets\n\tPut() error          // puts\n}\n\n" +
				"var f = func(a int) int {\n\treturn a\n}\n",
			lines: []int{4, 10},
		},
		"a declaration with no body": {
			src:   "package p\n\nfunc add(\n\ta, b int,\n) int\n",
			want:  "package p\n\nfunc add(a, b int) int\n",
			lines: []int{3},
		},
		"too long": {
			src: "package p\n\nfunc f(\n\t" + strings.Repeat("a", 160) + " int,\n\tb int,\n) {\n}\n",
		},
		"too long by its tabs": {
			src: "package p\n\nfunc g() {\n\t\t\t\t\t\tf := func(\n\t\t\t\t\t\t\t" + strings.Repeat("a", 146) + " int,\n\t\t\t\t\t\t) {\n\t\t\t\t\t\t}\n\t\t\t\t\t\t_ = f\n}\n",
		},
		"a comment, a string and a struct": {
			src: "package p\n\nfunc a(\n\tx int, // x\n) {\n}\n\nfunc b(\n\tx struct {\n\t\ty int `json:\"y\"`\n\t},\n) {\n}\n\nfunc c(\n\tx struct{},\n) {\n}\n",
		},
		"one line": {
			src: "package p\n\nfunc f(a int) {}\n",
		},
		"generated": {
			src: "// Code generated by x. DO NOT EDIT.\n\npackage p\n\nfunc f(\n\ta int,\n) {\n}\n",
		},
	} {
		t.Run(name, func(t *testing.T) {
			out, found, err := Join("p.go", []byte(c.src), limit)
			want := c.want
			if want == "" {
				want = c.src
			}
			if err != nil || string(out) != want {
				t.Fatalf("Join = %q, %v, want %q", out, err, want)
			}
			if len(found) != len(c.lines) {
				t.Fatalf("found %+v, want lines %v", found, c.lines)
			}
			for i, w := range found {
				if w.File != "p.go" || w.Line != c.lines[i] || w.Length > limit.MaxLen ||
					!strings.HasPrefix(w.String(), "p.go:") {
					t.Errorf("found %+v, want line %d", w, c.lines[i])
				}
			}
			again, more, err := Join("p.go", out, limit)
			if err != nil || len(more) != 0 || string(again) != string(out) {
				t.Errorf("Join again = %q, %+v, %v", again, more, err)
			}
		})
	}
	if _, _, err := Join("p.go", []byte("package p\nfunc ("), limit); err == nil {
		t.Error("a file that does not parse joined")
	}
}

// TestUnitWalk checks that Walk reports each signature that fits under
// its root with the file relative to the root, skips *.gen.go and the
// skipped directories, changes nothing until asked to write, then joins
// them in place so a second walk finds none, and stops at a file that
// does not parse or a root that does not exist.
func TestUnitWalk(t *testing.T) {
	root := t.TempDir()
	wrapped := "package p\n\nfunc f(\n\ta int,\n) {\n}\n"
	for _, name := range []string{
		"a/a.go", "a/a.gen.go", "a/testdata/t.go", "node_modules/m/m.go", ".claude/c.go", "notes.txt",
	} {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(wrapped), 0o640); err != nil {
			t.Fatal(err)
		}
	}
	found, err := Walk(root, limit, false)
	if err != nil || len(found) != 1 || found[0].File != "a/a.go" || found[0].Line != 3 {
		t.Fatalf("Walk = %+v, %v", found, err)
	}
	path := filepath.Join(root, "a", "a.go")
	if got, _ := os.ReadFile(path); string(got) != wrapped {
		t.Fatalf("a check wrote %q", got)
	}
	// Windows keeps no Unix permission bits, so the mode is compared with
	// the file's own before the write rather than with 0o640.
	before, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	if found, err := Walk(root, limit, true); err != nil || len(found) != 1 {
		t.Fatalf("Walk -w = %+v, %v", found, err)
	}
	got, _ := os.ReadFile(path)
	after, err := os.Stat(path)
	if err != nil || string(got) != "package p\n\nfunc f(a int) {\n}\n" ||
		after.Mode().Perm() != before.Mode().Perm() {
		t.Fatalf("joined %q, mode %v, was %v, %v", got, after.Mode().Perm(), before.Mode().Perm(), err)
	}
	if found, err := Walk(root, limit, false); err != nil || len(found) != 0 {
		t.Fatalf("Walk after joining = %+v, %v", found, err)
	}
	if got, _ := os.ReadFile(filepath.Join(root, "a", "a.gen.go")); string(got) != wrapped {
		t.Fatalf("a generated file was joined: %q", got)
	}
	if err := os.WriteFile(filepath.Join(root, "b.go"), []byte("package p\nfunc ("), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := Walk(root, limit, false); err == nil || !strings.Contains(err.Error(), "b.go") {
		t.Errorf("a file that does not parse: %v", err)
	}
	if _, err := Walk(filepath.Join(root, "gone"), limit, false); err == nil {
		t.Error("a root that does not exist was walked")
	}
}
