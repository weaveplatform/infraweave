var update = flag.Bool("update", false, "rewrite golden files")

const fixture = "testdata/ok"

func TestUnitBundleGolden(t *testing.T) {
	got, err := Bundle(fixture)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join("testdata", "golden", "ok.openapi.yaml")
	if *update {
		if err := os.WriteFile(path, got, filePerm); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run go test -update)", err)
	}
	if !bytes.Equal(want, got) {
		t.Errorf(
			"bundle differs from %s; run go test ./internal/openapibundle -update and review the diff",
			path,
		)
	}
}

// TestUnitBundleSemantics states what the golden file must show, so a
// reviewer of an -update diff knows what has to hold.
func TestUnitBundleSemantics(t *testing.T) {
	got, err := Bundle(fixture)
	if err != nil {
		t.Fatal(err)
	}
	text := string(got)
	if !strings.HasPrefix(text, "# Generated by `make bundle` from api/src/ok/;") {
		t.Errorf("missing generated header:\n%s", text)
	}
	if strings.Index(text, "/widgets:") > strings.Index(text, "/widgets/{widgetId}:") {
		t.Error("paths are not sorted")
	}
	if !strings.Contains(text, "# Kept:") {
		t.Error("fragment comments were dropped")
	}
	var doc struct {
		Components map[string]map[string]any `yaml:"components"`
	}
	if err := yaml.Unmarshal(got, &doc); err != nil {
		t.Fatal(err)
	}
	for kind, name := range map[string]string{
		"schemas": "Widget", "responses": "NotFound", "securitySchemes": "bearerAuth",
	} {
		if doc.Components[kind][name] == nil {
			t.Errorf("components/%s/%s missing", kind, name)
		}
	}
}

func TestUnitBundleDeterministic(t *testing.T) {
	first, err := Bundle(fixture)
	if err != nil {
		t.Fatal(err)
	}
	second, err := Bundle(fixture)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first, second) {
		t.Error("two bundles of the same fragments differ")
	}
}

// copyFixture returns a writable copy of the fixture with files replaced
// (or, for an empty body, removed).
func copyFixture(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := filepath.Join(t.TempDir(), "svc")
	if err := os.CopyFS(dir, os.DirFS(fixture)); err != nil {
		t.Fatal(err)
	}
	for name, body := range files {
		path := filepath.Join(dir, name)
		if body == "" {
			if err := os.Remove(path); err != nil {
				t.Fatal(err)
			}
			continue
		}
		if err := os.WriteFile(path, []byte(body), filePerm); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

const okPath = `paths:
  /gadgets:
    get:
      operationId: listGadgets
      responses:
        "200":
          description: ok
`

func TestUnitBundleErrors(t *testing.T) {
	for _, tc := range []struct {
		name  string
		files map[string]string
		want  error
		names []string // the error must name the file and the conflicting key
	}{
		{"missing info", map[string]string{InfoFile: ""}, ErrNoInfo, nil},
		{
			"info key",
			map[string]string{InfoFile: "openapi: 3.0.3\ninfo: {title: t, version: '1'}\npaths: {}\n"},
			ErrInfoKeys,
			[]string{InfoFile, `"paths"`},
		},
		{
			"version",
			map[string]string{InfoFile: "openapi: 3.1.0\ninfo: {title: t, version: '1'}\n"},
			ErrVersion,
			[]string{InfoFile},
		},
		{
			"fragment key",
			map[string]string{"paths-x.yaml": okPath + "tags: []\n"},
			ErrFragmentKeys,
			[]string{"paths-x.yaml", `"tags"`},
		},
		{
			"misnamed fragment",
			map[string]string{"widgets.yaml": "info: {title: t}\n"},
			ErrFragmentKeys,
			[]string{"widgets.yaml", `"info"`},
		},
		{
			"duplicate path",
			map[string]string{"paths-x.yaml": strings.ReplaceAll(okPath, "/gadgets", "/widgets")},
			ErrDuplicatePath,
			[]string{"paths-x.yaml", "/widgets", "paths-alpha.yaml"},
		},
		{
			"duplicate operationId",
			map[string]string{"paths-x.yaml": strings.ReplaceAll(okPath, "listGadgets", "listWidgets")},
			ErrDuplicateOpID,
			[]string{"paths-x.yaml", "listWidgets", "paths-alpha.yaml"},
		},
		{
			"duplicate component",
			map[string]string{"paths-x.yaml": "components:\n  schemas:\n    Widget: {type: string}\n"},
			ErrDuplicateComp,
			[]string{"paths-zeta.yaml", "schemas/Widget", "paths-x.yaml"},
		},
		{"paths not a mapping", map[string]string{"paths-x.yaml": "paths: []\n"}, ErrNotMapping, []string{"paths-x.yaml"}},
		{
			"components not a mapping",
			map[string]string{"paths-x.yaml": "components: []\n"},
			ErrNotMapping,
			[]string{"paths-x.yaml"},
		},
		{
			"component kind not a mapping",
			map[string]string{"paths-x.yaml": "components:\n  schemas: []\n"},
			ErrNotMapping,
			[]string{"paths-x.yaml", "components/schemas"},
		},
		{"top level not a mapping", map[string]string{"paths-x.yaml": "- a\n"}, ErrNotMapping, []string{"paths-x.yaml"}},
		{
			"dangling ref",
			map[string]string{"paths-x.yaml": strings.ReplaceAll(okPath, `description: ok`,
				"$ref: '#/components/responses/Missing'")},
			ErrInvalid,
			[]string{"Missing"},
		},
		{
			"invalid operation",
			map[string]string{"paths-x.yaml": "paths:\n  /gadgets:\n    get:\n      operationId: g\n"},
			ErrInvalid, nil,
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, err := Bundle(copyFixture(t, tc.files))
			if !errors.Is(err, tc.want) {
				t.Fatalf("got %v, want %v", err, tc.want)
			}
			for _, n := range tc.names {
				if !strings.Contains(err.Error(), n) {
					t.Errorf("%q does not name %s", err, n)
				}
			}
		})
	}
}

func TestUnitBundleUnreadable(t *testing.T) {
	if _, err := Bundle(copyFixture(t, map[string]string{"paths-x.yaml": "a: [\n"})); err == nil ||
		!strings.Contains(err.Error(), "parse") {
		t.Errorf("malformed YAML: got %v", err)
	}
	if _, err := Bundle(copyFixture(t, map[string]string{InfoFile: "a: [\n"})); err == nil ||
		errors.Is(err, ErrNoInfo) {
		t.Errorf("malformed info.yaml must not read as missing: got %v", err)
	}
	empty := copyFixture(t, map[string]string{"paths-x.yaml": "# nothing yet\n"})
	if _, err := Bundle(empty); err != nil {
		t.Errorf("an empty fragment is allowed: %v", err)
	}
	noComponents := copyFixture(t, map[string]string{
		InfoFile:                 "openapi: 3.0.3\ninfo: {title: t, version: '1'}\n",
		"components-common.yaml": "",
		"paths-zeta.yaml":        "",
		"paths-alpha.yaml":       okPath,
	})
	got, err := Bundle(noComponents)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(got), "components:") {
		t.Errorf("a bundle without components must not emit the key:\n%s", got)
	}
}

func TestUnitBundleAll(t *testing.T) {
	root := t.TempDir()
	if err := os.CopyFS(filepath.Join(root, "beta"), os.DirFS(fixture)); err != nil {
		t.Fatal(err)
	}
	if err := os.CopyFS(filepath.Join(root, "alpha"), os.DirFS(fixture)); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "README.md"), []byte("x"), filePerm); err != nil {
		t.Fatal(err)
	}
	out := t.TempDir()
	done, err := BundleAll(root, out)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(done, ",") != "alpha,beta" {
		t.Errorf("services = %v", done)
	}
	data, err := os.ReadFile(filepath.Join(out, "beta.openapi.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), "api/src/beta/") {
		t.Errorf("header names the wrong service:\n%.120s", data)
	}

	if _, err := BundleAll(filepath.Join(root, "missing"), out); err == nil {
		t.Error("missing source root: want error")
	}
	if err := os.Remove(filepath.Join(root, "alpha", InfoFile)); err != nil {
		t.Fatal(err)
	}
	if _, err := BundleAll(
		root,
		out,
	); !errors.Is(err, ErrNoInfo) ||
		!strings.HasPrefix(err.Error(), "alpha: ") {
		t.Errorf("broken service: got %v", err)
	}
	if err := os.RemoveAll(filepath.Join(root, "alpha")); err != nil {
		t.Fatal(err)
	}
	if _, err := BundleAll(root, filepath.Join(out, "missing")); err == nil {
		t.Error("unwritable output: want error")
	}
}
